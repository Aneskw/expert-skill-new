def add_molecule(mid, label, evidence, name=None, smiles=None, chirality="unresolved",
                 geometry="unresolved", representation="unresolved", stereo_note=None):
    ev = list(dict.fromkeys(evidence))
    m = st.new_molecule(mid, DOC, ev)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, ev)
    m["names"]["original"] = f(name or label, name or label, ev)
    m["names"]["english"] = f(name or label, name or label, ev)
    if smiles:
        m["representation_type"] = "smiles"
        m["smiles"] = f(
            f"structure/name for {label}", smiles, ev, method="structure_derivation",
            derivation="Candidate SMILES transcribed from the source drawing/name; parsing does not verify identity."
        )
        diag = st.stereo_inspect(smiles)
        rep_status = "partial" if any(x["specified"] == "Unspecified" for x in diag["potential_stereo"]) else "encoded"
        m["stereochemistry"]["isomeric_smiles"] = f(
            None, diag["canonical_isomeric_smiles"], ev, method="structure_derivation",
            derivation="Canonical isomeric SMILES generated by standard stereo from the candidate source-derived graph."
        )
        m["stereochemistry"]["identity_key"] = f(
            None, diag["stereo_graph_key"], ev, method="structure_derivation",
            derivation="stereo_graph_key generated by standard stereo; it is not a sample identity."
        )
        representation = rep_status
    else:
        m["representation_type"] = "unresolved"
        representation = "not_encoded" if representation == "unresolved" else representation
    for key, value in (("chirality_status", chirality), ("geometry_status", geometry),
                       ("representation_status", representation)):
        m["stereochemistry"][key] = f(
            None, value, ev, method="inference",
            derivation="Status assigned conservatively after inspecting the cited drawing/text; unspecified is not treated as achiral or racemic."
        )
    if stereo_note:
        m["stereochemistry"]["assignment"] = f(stereo_note, stereo_note, ev)
    m["identity_note"] = f(
        "Machine-created identity; exact structure and stereochemical encoding require expert review.",
        "Machine-created identity; exact structure and stereochemical encoding require expert review.", ev
    )
    molecules[mid] = m
    return m


def add_family(mid, label, evidence, description, variables):
    ev = list(evidence)
    m = add_molecule(mid, label, ev, name=label, representation="not_encoded")
    m["representation_type"] = "generic_template"
    m["smiles"] = f()
    m["generic_template"] = {
        "fixed_structure": f(description, {"description": description}, ev),
        "variables": [{
            "label": v,
            "attachment_points": f(f"{v} position shown in source drawing", {"label": v, "attachment": "source drawing"}, ev),
            "definition": f(f"{v} is a source-drawn variable substituent", "source-defined substituent", ev),
            "allowed_values": f("instances shown in the cited scope", "instances shown in the cited scope", ev),
            "constraints": f("not exhaustively defined in pages 1-6", "not exhaustively defined in pages 1-6", ev),
        } for v in variables],
        "instance_mapping": [],
        "reason": f("R-group scope drawing", "Generic source structure cannot be represented as one concrete SMILES.", ev),
    }
    return m


