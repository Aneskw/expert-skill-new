def fill_common(r, evidence, location, category, scheme=None, name="Pd-catalyzed unactivated C(sp3)-H olefination"):
    r["record_type"] = "specific_experiment"
    r["experiment_categories"] = f(category, [category], evidence)
    r["location"] = f(location, location, evidence)
    r["general_scheme_ids"] = [scheme] if scheme else []
    r["reaction_name"] = f(name, name, evidence)
    r["transformation_type"] = f(
        None, "intermolecular C(sp3)-H olefination/carbene coupling", evidence,
        method="inference", derivation="Transformation type normalized from the source reaction name and drawings."
    )
    r["procedure"]["original_text"] = f(location, location, evidence)
    r["procedure"]["general_procedure_reference"] = f(location, location, evidence)
    r["review"]["unresolved"] = [
        "Full product/substrate structures and complete stereochemical encoding require expert review.",
        "No explicitly associated SI was supplied; product-specific experimental details are unavailable.",
        "Bond classification is partial because no reviewed atom mapping is available.",
    ]
    r["completeness"] = "partial"


def common_participants(r, ref_mid, partner_mid, product_mid, evidence, scale=0.1, partner_amount=0.2,
                        solvent_mid="m_DMF", solvent_volume=1.0, include_product=True,
                        catalyst_mid="m_PdClAllyl_dimer", ligand_mid="m_tBuXPhos", base_mid="m_NaOAc"):
    parts = [participant("substrate_1", ref_mid, "reactant", evidence,
                         amount=(scale, "mmol", f"{scale:g} mmol"), equivalents=(1.0, "1.0 equiv"), reference=ref_mid),
             participant("substrate_2", partner_mid, "reactant", evidence,
                         amount=(partner_amount, "mmol", f"{partner_amount:g} mmol"), equivalents=(2.0, "2.0 equiv"), reference=ref_mid)]
    if catalyst_mid:
        parts.append(participant("catalyst", catalyst_mid, "catalyst", evidence,
                                 mol_percent=(5.0, "5 mol%"), reference=ref_mid))
    if ligand_mid:
        parts.append(participant("ligand", ligand_mid, "ligand", evidence,
                                 mol_percent=(30.0, "30 mol%"), reference=ref_mid))
    if base_mid:
        parts.append(participant("base", base_mid, "reagent", evidence,
                                 equivalents=(3.0, "3.0 equiv"), reference=ref_mid))
    parts.append(participant("solvent", solvent_mid, "solvent", evidence,
                             volume=(solvent_volume, "mL", f"{solvent_volume:g} mL")))
    if include_product and product_mid:
        parts.append(participant("product", product_mid, "product", evidence, product_role="main product"))
    r["participants"] = parts
    r["reaction_scale"] = f(
        f"{scale:g} mmol of aryl bromide", {"reference_molecule_id": ref_mid, "amount": quantity(scale, "mmol")}, evidence
    )
    r["solvent_conditions"]["composition"] = f(molecules[solvent_mid]["occurrences"][0]["compound_label"]["normalized_value"], solvent_mid, evidence)
    r["solvent_conditions"]["total_volume"] = f(f"{solvent_volume:g} mL", quantity(solvent_volume, "mL", f"{solvent_volume:g} mL"), evidence)


def add_generic_scheme(rid, page, label, reactants, product):
    evidence = [E[page]]
    r = st.new_reaction(f"{DOC}:{rid}", DOC, evidence)
    r["record_type"] = "generic_scheme"
    r["experiment_categories"] = f("substrate scope scheme", ["substrate_scope"], evidence)
    r["location"] = f(label, {"page": page, "region": label}, evidence)
    r["reaction_name"] = f("Pd-catalyzed unactivated C(sp3)-H olefination", "Pd-catalyzed unactivated C(sp3)-H olefination", evidence)
    r["transformation_type"] = f(None, "generic carbene-mediated olefination", evidence, method="inference", derivation="Normalized from figure title and arrow.")
    r["participants"] = [participant(f"family_reactant_{i+1}", mid, "reactant", evidence) for i, mid in enumerate(reactants)]
    r["participants"] += [
        participant("catalyst", "m_PdClAllyl_dimer", "catalyst", evidence, mol_percent=(5, "5 mol%"), reference=reactants[0]),
        participant("ligand", "m_tBuXPhos", "ligand", evidence, mol_percent=(30, "30 mol%"), reference=reactants[0]),
        participant("base", "m_NaOAc", "reagent", evidence, equivalents=(3, "3.0 equiv"), reference=reactants[0]),
        participant("solvent", "m_DMF", "solvent", evidence, volume=(1, "mL", "1 mL")),
        participant("family_product", product, "product", evidence, product_role="scope product family"),
    ]
    r["solvent_conditions"]["composition"] = f("DMF", "m_DMF", evidence)
    r["solvent_conditions"]["total_volume"] = f("1 mL", quantity(1, "mL", "1 mL"), evidence)
    add_step(r, evidence)
    r["procedure"]["original_text"] = f("conditions printed above the scope arrow", "conditions printed above the scope arrow", evidence)
    classify_success(r, evidence)
    r["review"]["unresolved"] = ["Generic R-group scheme; not a single concrete experiment.", "Variable structures and complete atom mapping are unresolved."]
    r["completeness"] = "partial"
    bundle["reactions"].append(r)
    return r["reaction_id"]


