def participant(pid, molecule_id, role, pages, *, amount=None, mass=None, volume=None, equiv=None, molpct=None, reference=None, stage="reaction"):
    p = st.new_participant(pid, molecule_id, role, ev(*pages), stage=stage)
    if amount is not None:
        p["charges"]["amount"] = src(f"{amount} mmol", q(amount, "mmol"), pages)
    if mass is not None:
        p["charges"]["mass"] = src(f"{mass} mg", q(mass, "mg"), pages)
    if volume is not None:
        p["charges"]["volume"] = src(f"{volume} mL", q(volume, "mL"), pages)
    if equiv is not None:
        p["charges"]["equivalents"] = src(f"{equiv} equiv", q(equiv, "equiv"), pages)
    if molpct is not None:
        p["charges"]["mol_percent"] = src(f"{molpct} mol%", q(molpct, "mol%"), pages)
    if reference is not None:
        p["equivalence_reference"] = infer(reference, pages, "Loading/equivalent denominator is the stated 0.20 mmol allenamide substrate.")
    return p


