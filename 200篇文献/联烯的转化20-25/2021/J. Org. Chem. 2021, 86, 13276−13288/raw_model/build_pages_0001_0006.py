def add_molecule(
    key: str,
    label: str,
    name: str,
    pages: tuple[int, ...],
    *,
    kind: str = "unresolved",
    smiles: str | None = None,
    chirality: str = "unresolved",
    geometry: str = "unresolved",
    representation: str | None = None,
    double_bonds=None,
    axial=None,
    mixture=None,
    assignment=None,
    identity_note: str | None = None,
):
    molecule_id = mid(key)
    if molecule_id in molecules:
        return molecule_id
    evidence = ev(*pages)
    m = st.new_molecule(molecule_id, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"] = [{
        "document_id": DOC,
        "compound_label": src(label, label, pages),
        "evidence_ids": evidence,
    }]
    m["names"]["original"] = src(name, name, pages)
    m["names"]["english"] = src(name, name, pages)
    m["names"]["abbreviations"] = src([label], [label], pages)
    m["names"]["aliases"] = src([], [], pages)
    m["cas_numbers"] = missing(pages)
    m["generic_template"] = None
    if smiles:
        diagnostic = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = derived(
            f"candidate SMILES derived from the source drawing for {label}",
            diagnostic["canonical_isomeric_smiles"],
            pages,
            "Manual graph transcription from the cited drawing followed by RDKit canonicalization; parsing is not chemical source verification.",
        )
        representation = representation or "encoded"
        m["stereochemistry"]["isomeric_smiles"] = derived(
            f"RDKit canonical isomeric SMILES for candidate {label}",
            diagnostic["canonical_isomeric_smiles"],
            pages,
            "Generated by standard stereo diagnostics from the candidate SMILES.",
        )
        m["stereochemistry"]["identity_key"] = derived(
            f"standard stereo graph key for candidate {label}",
            diagnostic["stereo_graph_key"],
            pages,
            "Generated by standard stereo diagnostics; this key does not establish sample identity.",
        )
    else:
        m["representation_type"] = kind
        m["smiles"] = missing(pages)
        representation = representation or "not_encoded"
        m["stereochemistry"]["isomeric_smiles"] = missing(pages)
        m["stereochemistry"]["identity_key"] = missing(pages)
    m["stereochemistry"]["atom_centers"] = missing(pages) if chirality == "unresolved" else infer([], pages, "No tetrahedral stereogenic center is asserted; status is based only on the cited drawing/candidate graph.")
    m["stereochemistry"]["double_bonds"] = src(double_bonds, double_bonds, pages) if double_bonds is not None else missing(pages)
    m["stereochemistry"]["axial"] = src(axial, axial, pages) if axial is not None else missing(pages)
    m["stereochemistry"]["mixture"] = src(mixture, mixture, pages) if mixture is not None else missing(pages)
    m["stereochemistry"]["assignment"] = src(assignment, assignment, pages) if assignment is not None else missing(pages)
    m["stereochemistry"]["chirality_status"] = infer(chirality, pages, "Stereo status assessed from the cited source drawing; absence of a descriptor is not interpreted as racemic.")
    m["stereochemistry"]["geometry_status"] = infer(geometry, pages, "Geometry status assessed from the cited source drawing and explicit E-selectivity statements.")
    m["stereochemistry"]["representation_status"] = infer(representation, pages, "Reports whether the retained candidate SMILES encodes all source stereochemical information.")
    m["identity_note"] = src(
        identity_note or ("Source-labeled molecule; complete structure not encoded because the compact drawing was not independently structure-verified." if not smiles else "Candidate graph retained for review; RDKit parsing is not source verification."),
        identity_note or ("Source-labeled molecule; complete structure not encoded because the compact drawing was not independently structure-verified." if not smiles else "Candidate graph retained for review; RDKit parsing is not source verification."),
        pages,
    )
    m["external_properties"] = []
    molecules[molecule_id] = m
    bundle["molecules"].append(m)
    return molecule_id


