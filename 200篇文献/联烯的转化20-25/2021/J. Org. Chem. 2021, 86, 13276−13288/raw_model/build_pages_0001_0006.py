def ev(*pages: int) -> list[str]:
    ids: list[str] = []
    for page in pages:
        ids += [f"{DOC}:page{page}:image", f"{DOC}:page{page}:text"]
    return ids


def src(raw, normalized=None, pages=(1,), status="pending_review"):
    if normalized is None:
        normalized = copy.deepcopy(raw)
    return st.fact(raw, normalized, ev(*pages), method="original_extraction", status=status)


def inherited(raw, normalized=None, pages=(3,), derivation="Inherited from the explicitly stated table/scheme conditions."):
    if normalized is None:
        normalized = copy.deepcopy(raw)
    return st.fact(raw, normalized, ev(*pages), method="inherited_general_condition", derivation=derivation)


def infer(normalized, pages=(1,), derivation="Structure or reaction-class inference from the cited source drawing."):
    return st.fact(None, normalized, ev(*pages), method="inference", derivation=derivation)


def derived(raw, normalized, pages=(1,), derivation="Derived from the cited source structure; not source-verified SMILES."):
    return st.fact(raw, normalized, ev(*pages), method="structure_derivation", derivation=derivation)


def missing(pages=(1,), status="unreported"):
    return st.fact(evidence=ev(*pages), status=status)


def q(number, unit, **extra):
    result = {"number": number, "unit": unit}
    result.update(extra)
    return result


