def template_molecule(mid, label, name, evidence, fixed, variables, reason,
                      *, chirality="unresolved", geometry="unspecified",
                      representation="not_encoded", assignment=None):
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, evidence)
    set_name(m, name, evidence=evidence)
    m["representation_type"] = "generic_template"
    m["smiles"] = missing(evidence)
    m["generic_template"] = {
        "fixed_structure": f(fixed, fixed, evidence),
        "variables": [],
        "instance_mapping": [],
        "reason": f(reason, reason, evidence),
    }
    for item in variables:
        m["generic_template"]["variables"].append({
            "label": item["label"],
            "attachment_points": f(item.get("attachment"), item.get("attachment"), evidence),
            "definition": f(item.get("definition"), item.get("definition"), evidence),
            "allowed_values": f(item.get("allowed"), item.get("allowed"), evidence) if item.get("allowed") is not None else missing(evidence),
            "constraints": f(item.get("constraints"), item.get("constraints"), evidence) if item.get("constraints") is not None else missing(evidence),
        })
    set_status(m, chirality, geometry, representation, evidence,
               assignment=assignment or {"status": "not completely assigned by the source/template"})
    m["identity_note"] = f(reason, reason, evidence)
    return m


def participant(pid, mid, role, evidence, stage="reaction"):
    return st.new_participant(pid, mid, role, evidence, stage=stage)


def q(number, unit, raw=None, qualifier=None):
    value = {"number": number, "unit": unit}
    if raw is not None:
        value["raw_text"] = raw
    if qualifier is not None:
        value["qualifier"] = qualifier
    return value


