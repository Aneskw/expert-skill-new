def concrete_molecule(mid, label, name, smiles, evidence, *, achiral=True):
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, evidence)
    set_name(m, name, evidence=evidence)
    m["representation_type"] = "smiles"
    m["smiles"] = derived(
        "candidate transcribed from the source drawing; no SMILES is printed in the article",
        smiles, evidence,
        "Connectivity was manually transcribed from the inspected Scheme 1/Figure 4 drawing and remains a machine candidate."
    )
    m["generic_template"] = None
    diag = st.stereo_inspect(smiles)
    m["stereochemistry"]["isomeric_smiles"] = derived(
        "RDKit graph diagnostic of the candidate connectivity",
        diag["canonical_isomeric_smiles"], evidence,
        "Generated by standard stereo from the candidate SMILES; this does not verify the source drawing."
    )
    m["stereochemistry"]["identity_key"] = derived(
        "RDKit stereo_graph_key for the candidate connectivity",
        diag["stereo_graph_key"], evidence,
        "Generated by standard stereo; it is a graph comparison key, not a sample identity."
    )
    if achiral:
        assignment = {"source_statement": "achiral allene monomers", "candidate_note": "one allene terminus is CH2"}
        set_status(m, "achiral", "not_applicable", "partial", evidence, assignment=assignment)
    m["identity_note"] = f(
        "The article gives a full drawing but no source SMILES or CAS number.",
        "Candidate connectivity needs expert comparison to the drawing; allene toolkit stereo support is limited.",
        evidence,
    )
    return m, diag


