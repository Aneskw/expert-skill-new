def add_outcome(r, oid, kind, target, raw, normalized, evidence, *, basis_raw=None,
                basis_norm=None, product_role="main product", yield_type=None, scope=None,
                status=None, alternatives=()):
    o = st.new_outcome(oid, kind, [target] if target else [], evidence)
    o["product_role"] = f(product_role, product_role, evidence) if product_role else missing(evidence)
    if alternatives:
        o["value"] = f(raw, None, evidence, status="conflict")
        o["value"]["alternatives"] = list(alternatives)
    else:
        o["value"] = f(raw, normalized, evidence, status=status)
    o["yield_type"] = f(yield_type, yield_type, evidence) if yield_type else missing(evidence)
    o["measurement_basis"] = f(basis_raw, basis_norm, evidence) if basis_raw is not None else missing(evidence)
    o["scope"] = f(scope, scope, evidence) if scope is not None else missing(evidence)
    r["outcomes"].append(o)


def product_template(mid, label, monomer, evidence, helix=None):
    if helix == "left":
        chirality = "specified"
        assignment = {"macromolecular_helicity": "predominantly left-handed", "source": "CD and AFM"}
    elif helix == "right":
        chirality = "specified"
        assignment = {"macromolecular_helicity": "predominantly right-handed", "source": "CD and AFM"}
    elif helix == "predominant_unassigned":
        chirality = "partially_specified"
        assignment = {"macromolecular_helicity": "predominantly one-handed", "absolute_hand": "unassigned for this sample"}
    else:
        chirality = "unresolved"
        assignment = {"macromolecular_helicity": "not assigned for this Table 1 sample"}
    return template_molecule(
        mid, label, label, evidence,
        fixed={"transformation": "2,3-polymerized allene repeat unit retaining an exo C=C pendant", "source_monomer": monomer},
        variables=[{"label": "n", "definition": "unspecified degree of polymerization", "attachment": "repeat-unit chain ends"}],
        reason="Polymer has unspecified chain length and chain ends; the exo-double-bond syn/anti configuration was not determined.",
        chirality=chirality, geometry="unspecified", representation="not_encoded", assignment=assignment,
    )


