def set_name(m, original, english=None, abbreviations=None, aliases=None, evidence=()):
    m["names"]["original"] = f(original, original, evidence)
    m["names"]["english"] = f(english or original, english or original, evidence)
    m["names"]["abbreviations"] = f(abbreviations, abbreviations, evidence) if abbreviations else missing(evidence)
    m["names"]["aliases"] = f(aliases, aliases, evidence) if aliases else missing(evidence)
    m["cas_numbers"] = missing(evidence)


