def participant(r, pid, mid, role, ev, *, stage="reaction", product_role=None,
                amount=None, mass=None, volume=None, equiv=None, molpct=None,
                ref=None, method="original_extraction"):
    p = st.new_participant(pid, mid, role, ev, stage)
    if product_role:
        p["product_role"] = f(product_role, product_role, ev)
    if amount:
        add_charge(p, "amount", amount[0], amount[1], ev, method)
    if mass:
        add_charge(p, "mass", mass[0], mass[1], ev, method)
    if volume:
        add_charge(p, "volume", volume[0], volume[1], ev, method)
    if equiv:
        add_charge(p, "equivalents", equiv[0], equiv[1], ev, method)
    if molpct:
        add_charge(p, "mol_percent", molpct[0], molpct[1], ev, method)
    if ref:
        p["equivalence_reference"] = f(ref, ref, ev, method)
    r["participants"].append(p)
    return p


