def common(key, evidence):
    label, smiles = COMMON_SMILES[key]
    return ensure_molecule(key, label, evidence, representation="smiles", smiles=smiles, common=True)


def source_label(key, label, evidence, stereo_kind="unresolved", assignment=None, axial=None, mixture=None, note=None):
    return ensure_molecule(key, label, evidence, chiral=stereo_kind, assignment=assignment,
                           axial=axial, mixture=mixture, identity_note=note)


def add_charge(participant, field, raw, normalized, evidence):
    participant["charges"][field] = f(raw, normalized, evidence)


def participant(pid, mid, role, evidence, *, product_role=None, amount=None, mass=None,
                volume=None, equivalents=None, mol_percent=None, reference=None, stage="reaction"):
    p = st.new_participant(pid, mid, role, evidence, stage=stage)
    if product_role is not None:
        p["product_role"] = f(product_role, product_role, evidence)
    for field, item in (("amount", amount), ("mass", mass), ("volume", volume),
                        ("equivalents", equivalents), ("mol_percent", mol_percent)):
        if item is not None:
            raw, normalized = item
            add_charge(p, field, raw, normalized, evidence)
    if reference is not None:
        p["equivalence_reference"] = f(reference, reference, evidence)
    return p


def classification(evidence, labels=("C-C", "C-H"), coverage="partial", limitation=None):
    changes = []
    label_rows = []
    for i, code in enumerate(labels, 1):
        if code == "C-C":
            atoms = [{"atom_map": None, "element": "C"}, {"atom_map": None, "element": "C"}]
        elif code == "C-H":
            atoms = [{"atom_map": None, "element": "C"}, {"atom_map": None, "element": "H"}]
        elif code == "DB-C-O":
            atoms = [{"atom_map": None, "element": "C"}, {"atom_map": None, "element": "O"}]
        else:
            raise ValueError(code)
        change = {"change_id": f"b{i}", "atoms": atoms,
                  "before_order": 1 if code == "DB-C-O" else 0,
                  "after_order": 2 if code == "DB-C-O" else 1,
                  "change_type": "order_increased" if code == "DB-C-O" else ("hydrogen_gain" if code == "C-H" else "formed")}
        changes.append(f(None, change, evidence, method="structure_derivation",
                         derivation="Net bond-change class inferred from the source-drawn reactant/product transformation; atom mapping is unresolved."))
        lab = st.bond_label(atoms[0]["element"], atoms[1]["element"], change["after_order"])
        lab["supporting_change_ids"] = [change["change_id"]]
        label_rows.append(lab)
    return {
        "standard_id": st.STANDARD,
        "mapped_reaction_smiles": f(),
        "bond_changes": changes,
        "labels": f(None, label_rows, evidence, method="structure_derivation",
                    derivation="Labels computed from the explicitly retained partial bond changes; no atom-mapped reaction is claimed."),
        "coverage": f(None, coverage, evidence, method="inference",
                      derivation="Compact main-text drawings do not support complete atom mapping."),
        "limitations": [limitation or "Partial graph interpretation only; exact atom mapping, bond-order changes, and hydrogen source remain unresolved."],
        "model_votes": [],
    }


def unresolved_classification(evidence, not_applicable=False, why=None):
    status = "not_applicable" if not_applicable else "unresolved"
    return {
        "standard_id": st.STANDARD,
        "mapped_reaction_smiles": f(),
        "bond_changes": [],
        "labels": f(None, [], evidence, method="inference",
                    derivation=why or "No formed-bond label asserted from the available observation."),
        "coverage": f(None, status, evidence, method="inference",
                      derivation=why or "Observed result does not support a complete transformation classification."),
        "limitations": [why or "No complete atom-mapped transformation is available."],
        "model_votes": [],
    }


def base_reaction(rid, page, location, categories, name, transformation, evidence=None):
    evidence = evidence or ev(page)
    r = st.new_reaction(f"{DOC}:{rid}", DOC, evidence)
    r["record_type"] = "specific_experiment"
    r["experiment_categories"] = f(categories, categories, evidence)
    r["location"] = f(location, {"page": page, "location": location}, evidence)
    r["reaction_name"] = f(name, name, evidence)
    r["transformation_type"] = f(None, transformation, evidence, method="inference",
                                  derivation="Transformation type normalized from the source table/scheme heading and drawings.")
    r["review"] = {"status": "needs_review", "method": "model", "reviewer": None,
                   "checked_fields": [], "unresolved": []}
    r["completeness"] = "partial"
    return r


def set_scale(r, raw, ref_mid, amount, evidence):
    r["reaction_scale"] = f(raw, {"reference_molecule_id": ref_mid, "amount": amount}, evidence)


def set_solvent(r, label, mid, volume, evidence, ratio=None):
    r["solvent_conditions"]["composition"] = f(label, [mid], evidence)
    if volume is not None:
        r["solvent_conditions"]["total_volume"] = f(f"{volume} mL", q(volume, "mL"), evidence)
    if ratio is not None:
        r["solvent_conditions"]["mixture_ratio"] = f(ratio, ratio, evidence)


def add_step(r, sid, evidence, pids, operation, temperature=None, time=None, atmosphere=None, stage="reaction"):
    s = st.new_step(sid, evidence, stage=stage)
    s["participant_ids"] = list(pids)
    s["operation"] = f(operation, operation, evidence)
    if temperature is not None:
        raw, normalized = temperature
        s["temperature"] = f(raw, normalized, evidence)
    if time is not None:
        raw, normalized = time
        s["time"] = f(raw, normalized, evidence)
    if atmosphere is not None:
        s["atmosphere"] = f(atmosphere, atmosphere, evidence)
    r["steps"].append(s)


def add_outcome(r, oid, kind, targets, raw, normalized, evidence, *, basis=None,
                yield_type=None, scope=None, product_role=None):
    o = st.new_outcome(oid, kind, targets, evidence)
    o["value"] = f(raw, normalized, evidence)
    if basis is not None:
        o["measurement_basis"] = f(basis, basis, evidence)
    if yield_type is not None:
        o["yield_type"] = f(yield_type, yield_type, evidence)
    if scope is not None:
        o["scope"] = f(scope, scope, evidence)
    if product_role is not None:
        o["product_role"] = f(product_role, product_role, evidence)
    r["outcomes"].append(o)


def add_note(r, raw, evidence, normalized=None, method="original_extraction", derivation=None):
    r["notes"].append(f(raw, normalized if normalized is not None else raw, evidence,
                        method=method, derivation=derivation))


