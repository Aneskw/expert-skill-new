def ensure_molecule(key, label, evidence, *, chiral="unresolved", geometry="unresolved",
                    assignment=None, axial=None, mixture=None, identity_note=None,
                    representation="unresolved", smiles=None, common=False):
    mid = f"mol_{DOC[4:12]}_{key}"
    if mid in molecules:
        m = molecules[mid]
        occ = m["occurrences"][0]
        for eid in evidence:
            if eid not in occ["evidence_ids"]:
                occ["evidence_ids"].append(eid)
            for target in (occ["compound_label"], m["names"]["original"], m["identity_note"]):
                if target["normalized_value"] is not None and eid not in target["evidence_ids"]:
                    target["evidence_ids"].append(eid)
        return mid
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, evidence)
    m["names"]["original"] = f(label, label, evidence)
    m["names"]["english"] = f()
    m["names"]["abbreviations"] = f()
    m["names"]["aliases"] = f()
    m["cas_numbers"] = f()
    if representation == "smiles":
        m["representation_type"] = "smiles"
        m["smiles"] = f(smiles, smiles, evidence)
        diag = st.stereo_inspect(smiles)
        m["stereochemistry"]["chirality_status"] = f(
            "graph inspected", "achiral", evidence, method="structure_derivation",
            derivation="standard stereo found no assigned or potential atom/axial stereochemistry in this candidate graph.")
        has_db = any(d["stereo"] != "STEREONONE" for d in diag["double_bonds"])
        m["stereochemistry"]["geometry_status"] = f(
            "graph inspected", "specified" if has_db else "not_applicable", evidence,
            method="structure_derivation",
            derivation="standard stereo diagnostics on the candidate SMILES; this does not verify source identity.")
        m["stereochemistry"]["representation_status"] = f(
            "candidate SMILES", "encoded" if has_db else "not_applicable", evidence,
            method="structure_derivation",
            derivation="Candidate graph was parsed with standard stereo; identity remains machine-extracted.")
        m["stereochemistry"]["isomeric_smiles"] = f(
            smiles, diag["canonical_isomeric_smiles"], evidence, method="structure_derivation",
            derivation="Canonical isomeric SMILES generated by standard stereo.")
        m["stereochemistry"]["identity_key"] = f(
            None, diag["stereo_graph_key"], evidence, method="structure_derivation",
            derivation="Stereo graph key generated by standard stereo; not a sample identity.")
        m["identity_note"] = f(
            identity_note or "Candidate structure derived from an unambiguous formula/name in the source; parsing is not source verification.",
            identity_note or "Candidate structure; identity remains needs_review.", evidence)
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = f()
        m["stereochemistry"]["chirality_status"] = f(label, chiral, evidence)
        m["stereochemistry"]["geometry_status"] = f(label, geometry, evidence)
        m["stereochemistry"]["representation_status"] = f(
            "compact source drawing not encoded", "not_encoded" if chiral in {"specified", "racemic", "mixture", "partially_specified"} else "unresolved", evidence)
        if assignment is not None:
            m["stereochemistry"]["assignment"] = f(assignment, assignment, evidence)
        if axial is not None:
            m["stereochemistry"]["axial"] = f(axial, axial, evidence)
        if mixture is not None:
            m["stereochemistry"]["mixture"] = f(mixture, mixture, evidence)
        m["identity_note"] = f(
            identity_note or "Source-labelled compact drawing retained without a concrete SMILES; connectivity/stereochemical encoding requires SI-quality review.",
            identity_note or "Structure unresolved from the supplied main-text drawing.", evidence)
    m["external_properties"] = []
    molecules[mid] = m
    return mid


def generic_molecule(key, label, evidence, variables):
    mid = ensure_molecule(key, label, evidence, identity_note="Generic R-group structure in Scheme 1c3; no concrete molecule asserted.")
    m = molecules[mid]
    m["representation_type"] = "generic_template"
    m["generic_template"] = {
        "fixed_structure": f(label, {"source_scaffold": label}, evidence),
        "variables": [{
            "label": var,
            "attachment_points": f(f"{var} attachment shown in Scheme 1c3", None, evidence,
                                   status="unreadable"),
            "definition": f(var, var, evidence),
            "allowed_values": f(),
            "constraints": f(),
        } for var in variables],
        "instance_mapping": [],
        "reason": f("R-group drawing", "The main-text scheme defines a family rather than one concrete molecule.", evidence),
    }
    m["stereochemistry"]["chirality_status"] = f(label, "unresolved", evidence)
    m["stereochemistry"]["geometry_status"] = f(label, "unresolved", evidence)
    m["stereochemistry"]["representation_status"] = f(label, "unresolved", evidence)
    return mid


