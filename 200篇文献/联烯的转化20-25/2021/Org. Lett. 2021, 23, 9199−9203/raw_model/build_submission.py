    r["reaction_name"] = F(name, name, ev)
    r["transformation_type"] = inferred(transformation, ev, "Transformation summarized from the cited source region.")
    r["classification"] = classify(class_kind, ev)
    r["review"] = {
        "status": "needs_review", "method": "model", "reviewer": None,
        "checked_fields": [],
        "unresolved": ["Supporting Information was advertised but not supplied or explicitly associated.",
                       "Machine record requires expert source review; schema validity is not chemistry certification."]
    }
    r["completeness"] = "partial"
    return r


