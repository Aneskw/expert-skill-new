def f(raw=None, normalized=None, evidence=(), method="original_extraction", derivation=None,
      status=None):
    return st.fact(raw, normalized, evidence, method=method, derivation=derivation, status=status)


def derived(raw, normalized, evidence, derivation):
    return f(raw, normalized, evidence, method="structure_derivation", derivation=derivation)


def inferred(raw, normalized, evidence, derivation):
    return f(raw, normalized, evidence, method="inference", derivation=derivation)


def set_status(m, key, normalized, evidence, derivation, raw="source structure drawing"):
    m["stereochemistry"][key] = derived(raw, normalized, evidence, derivation)


def molecule(mid, label, evidence, name=None, smiles=None, chirality="unresolved",
             geometry="not_applicable", representation="unresolved", identity_note=None,
             axial=None, double_bonds=None, mixture=None, assignment=None):
    evidence = list(evidence)
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, evidence)
    source_name = name or label
    m["names"]["original"] = f(source_name, source_name, evidence)
    m["names"]["english"] = f(source_name, source_name, evidence)
    m["names"]["abbreviations"] = f()
    m["names"]["aliases"] = f()
    m["cas_numbers"] = f()
    if smiles:
        m["representation_type"] = "smiles"
        m["smiles"] = derived(
            {"source": "structure drawing or explicit reagent name", "compound_label": label},
            smiles,
            evidence,
            "Candidate connectivity transcribed from the supplied page image/name; parsing does not certify source correctness.",
        )
        diag = st.stereo_inspect(smiles)
        m["stereochemistry"]["identity_key"] = derived(
            {"candidate_smiles": smiles}, diag["stereo_graph_key"], evidence,
            "Generated by standard stereo graph diagnostics from the candidate SMILES."
        )
        if representation in ("not_applicable", "encoded"):
            m["stereochemistry"]["isomeric_smiles"] = derived(
                {"candidate_smiles": smiles}, diag["canonical_isomeric_smiles"], evidence,
                "Canonical isomeric SMILES generated by standard stereo diagnostics; no extra configuration was inferred."
            )
        else:
            m["stereochemistry"]["isomeric_smiles"] = f()
        if diag["atom_centers"]:
            m["stereochemistry"]["atom_centers"] = derived(
                "candidate graph diagnostics", diag["atom_centers"], evidence,
                "Potential/assigned atom centers calculated from the candidate graph; '?' remains unassigned."
            )
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = f()
        m["stereochemistry"]["isomeric_smiles"] = f()
        m["stereochemistry"]["identity_key"] = f()
    set_status(m, "chirality_status", chirality, evidence,
               "Status follows visible stereochemical marks and the candidate graph; missing marks are not interpreted as racemic.")
    set_status(m, "geometry_status", geometry, evidence,
               "Status follows the depicted unsaturation and the paper's E/Z statements where applicable.")
    set_status(m, "representation_status", representation, evidence,
               "Status states whether the retained molecular representation encodes the source stereochemical information.")
    m["stereochemistry"]["axial"] = (
        derived("source allene drawing", axial, evidence,
                "The terminal allene has two identical substituents at one terminus, so no configurationally stable allene axis is assigned.")
        if axial is not None else f()
    )
    m["stereochemistry"]["double_bonds"] = (
        f("source E/Z statement or structure drawing", double_bonds, evidence)
        if double_bonds is not None else f()
    )
    m["stereochemistry"]["mixture"] = (
        f("products were obtained as a mixture of inseparable E and Z isomers", mixture, evidence)
        if mixture is not None else f()
    )
    m["stereochemistry"]["assignment"] = (
        f("The preference for Z geometry was established by analogy with similar molecules [8-9].",
          assignment, evidence) if assignment is not None else f()
    )
    m["identity_note"] = f(identity_note, identity_note, evidence) if identity_note else f()
    m["external_properties"] = []
    return m


def template_molecule(mid, label, fixed, variables, evidence, reason):
    m = molecule(mid, label, evidence, name=label, chirality="unresolved",
                 geometry="unresolved", representation="not_encoded", identity_note=reason)
    m["representation_type"] = "generic_template"
    m["smiles"] = f()
    m["generic_template"] = {
        "fixed_structure": f(fixed, {"source_notation": fixed}, evidence),
        "variables": [
            {
                "label": var,
                "attachment_points": f(f"{var} attachment shown in {fixed}", ["source-depicted attachment"], evidence),
                "definition": f(definition, definition, evidence),
                "allowed_values": f(),
                "constraints": f(),
            }
            for var, definition in variables
        ],
        "instance_mapping": [],
        "reason": f(reason, reason, evidence),
    }
    return m


def product_molecule(number, ratio, evidence=(E2I, E2T)):
    e, z = ratio
    if e == 0:
        geometry = "specified"
        double_bonds = [{"alkene": "new internal alkene", "configuration": "Z", "reported_ratio": f"{e}:{z}"}]
        mixture_value = None
        note = f"Product {number}; Z structure shown and E/Z reported as 0:100; assignment is by analogy, not an independent absolute method."
    else:
        geometry = "mixture"
        double_bonds = [{"alkene": "new internal alkene", "components": ["E", "Z"], "reported_ratio": f"{e}:{z}"}]
        mixture_value = {"type": "E/Z mixture", "ratio_reported_in_experiment": f"{e}:{z}", "major": "Z"}
        note = f"Product {number} is an inseparable E/Z mixture; Fig. 1 or Fig. 2 depicts the major Z isomer."
    return molecule(
        f"{DOC}:mol_product_{number}", f"{number}", evidence,
        name=f"product {number}", smiles=None, chirality="unresolved", geometry=geometry,
        representation="not_encoded", identity_note=note, double_bonds=double_bonds,
        mixture=mixture_value,
        assignment={"major_isomer": "Z", "assignment_method": "analogy with similar molecules [8-9]"},
    )


def participant(pid, mid, role, evidence, stage="reaction", product_role=None):
    p = st.new_participant(pid, mid, role, evidence, stage=stage)
    if product_role is not None:
        p["product_role"] = f(product_role, product_role, evidence)
    return p


def charge(p, key, raw, normalized, evidence, reference_mid, inherited=False):
    method = "inherited_general_condition" if inherited else "original_extraction"
    p["charges"][key] = f(raw, normalized, evidence, method=method)
    p["equivalence_reference"] = inferred(
        {"scheme_reference": "substrate shown first in the reaction scheme"}, reference_mid, evidence,
        "The scheme expresses equivalents/mol% relative to the first substrate; the row-specific substrate is used as denominator."
    )


def set_common_reaction(r, record_type, category, location_raw, location_norm, evidence,
                        reaction_name, transformation):
    r["record_type"] = record_type
    r["experiment_categories"] = f(category, [category], evidence)
    r["location"] = f(location_raw, location_norm, evidence)
    r["reaction_name"] = f(reaction_name, reaction_name, evidence)
    r["transformation_type"] = inferred(
        transformation, transformation, evidence,
        "Transformation type normalized from the source reaction drawing and accompanying prose."
    )
    r["review"] = {
        "status": "needs_review", "method": "model", "reviewer": None, "checked_fields": [],
        "unresolved": [],
    }
    r["completeness"] = "partial"


def set_solvent(r, raw, normalized, evidence, inherited=False):
    r["solvent_conditions"]["composition"] = f(
        raw, normalized, evidence,
        method="inherited_general_condition" if inherited else "original_extraction"
    )


def set_procedure(r, raw, evidence, inherited=False):
    r["procedure"]["original_text"] = f(
        raw, raw, evidence,
        method="inherited_general_condition" if inherited else "original_extraction"
    )
    r["procedure"]["general_procedure_reference"] = f(
        "reaction conditions printed over the scheme arrow",
        "reaction conditions printed over the scheme arrow",
        evidence,
        method="inherited_general_condition" if inherited else "original_extraction",
    )


def reaction_step(step_id, evidence, participant_ids, temperature_raw, time_hours, inherited=False):
    s = st.new_step(step_id, evidence)
    s["participant_ids"] = list(participant_ids)
    method = "inherited_general_condition" if inherited else "original_extraction"
    s["operation"] = f("heated at reflux", "heated at reflux", evidence, method=method)
    s["temperature"] = f(temperature_raw, temperature_raw, evidence, method=method)
    s["time"] = f(f"{time_hours} h", {"number": time_hours, "unit": "h"}, evidence, method=method)
    return s


