def ev(page: int) -> list[str]:
    return [f"{DOC}:page{page}:text", f"{DOC}:page{page}:image"]


def q(number, unit, raw_text=None, **extra):
    value = {"number": number, "unit": unit}
    if raw_text is not None:
        value["raw_text"] = raw_text
    value.update(extra)
    return value


def f(raw=None, normalized=None, evidence=(), method="original_extraction",
      status=None, derivation=None):
    return st.fact(raw, normalized, evidence, method=method, status=status,
                   derivation=derivation)


def derived(normalized, evidence, derivation):
    return f(None, normalized, evidence, method="structure_derivation",
             derivation=derivation)


def inferred(normalized, evidence, derivation):
    return f(None, normalized, evidence, method="inference", derivation=derivation)


def raw_only(raw, evidence):
    return f(raw, None, evidence, status="pending_review")


MOLECULES = {}


def molecule(mid, label, page, english=None, smiles=None, stereo=None,
             identity_note=None):
    evidence = ev(page)
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, evidence)
    m["names"]["original"] = f(label, label, evidence)
    if english:
        m["names"]["english"] = f(english, english, evidence)
    m["cas_numbers"] = f(evidence=evidence)
    m["external_properties"] = []
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = derived(
            smiles, evidence,
            "Candidate connectivity was manually transcribed from the source drawing/name; "
            "RDKit parsing and graph diagnostics do not verify source identity.",
        )
        m["stereochemistry"]["isomeric_smiles"] = derived(
            diag["canonical_isomeric_smiles"], evidence,
            "RDKit canonical isomeric SMILES generated from the manually transcribed candidate.",
        )
        m["stereochemistry"]["identity_key"] = derived(
            diag["stereo_graph_key"], evidence,
            "SHA-256 stereo graph key generated by standard stereo; it is not a sample identity.",
        )
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = f(evidence=evidence)
    stereo = stereo or {}
    for key in ("atom_centers", "double_bonds", "axial", "mixture", "assignment"):
        if key in stereo:
            raw, norm = stereo[key]
            m["stereochemistry"][key] = f(raw, norm, evidence)
        else:
            m["stereochemistry"][key] = f(evidence=evidence)
    for key, default in (
        ("chirality_status", "unresolved"),
        ("geometry_status", "unresolved"),
        ("representation_status", "partial" if smiles else "unresolved"),
    ):
        value = stereo.get(key, default)
        if isinstance(value, tuple):
            m["stereochemistry"][key] = f(value[0], value[1], evidence)
        else:
            m["stereochemistry"][key] = inferred(
                value, evidence,
                "Stereo status assigned conservatively from the displayed structure/name and the "
                "limits of the retained representation; absence of a tag is not treated as racemic.",
            )
    m["identity_note"] = f(
        identity_note, identity_note, evidence
    ) if identity_note else f(evidence=evidence)
    MOLECULES[mid] = m
    return mid


def template_molecule(mid, label, page, fixed, variables):
    evidence = ev(page)
    molecule(mid, label, page, identity_note="Generic source drawing; not a concrete compound identity.")
    m = MOLECULES[mid]
    m["representation_type"] = "generic_template"
    m["smiles"] = f(evidence=evidence)
    m["generic_template"] = {
        "fixed_structure": f(fixed, {"description": fixed}, evidence),
        "variables": [
            {
                "label": v,
                "attachment_points": f(f"source drawing attachment for {v}", f"source drawing attachment for {v}", evidence),
                "definition": f(desc, desc, evidence),
                "allowed_values": f(evidence=evidence),
                "constraints": f(evidence=evidence),
            }
            for v, desc in variables
        ],
        "instance_mapping": [],
        "reason": f("R-group/generic drawing", "Source uses variable substituents; no unique concrete SMILES exists.", evidence),
    }
    m["stereochemistry"]["representation_status"] = inferred(
        "not_encoded", evidence, "Generic variable structure cannot encode a unique stereoisomer."
    )
    return mid


