REACTIONS = []


def participant(pid, mid, role, evidence, *, stage="reaction", product_role=None,
                mass=None, amount=None, volume=None, equivalents=None, mol_percent=None,
                reference=None):
    p = st.new_participant(pid, mid, role, evidence, stage=stage)
    if product_role:
        p["product_role"] = f(product_role, product_role, evidence)
    values = {"mass": mass, "amount": amount, "volume": volume,
              "equivalents": equivalents, "mol_percent": mol_percent}
    for key, pair in values.items():
        if pair is not None:
            p["charges"][key] = f(pair[0], pair[1], evidence)
    if reference:
        p["equivalence_reference"] = f(reference, reference, evidence)
    return p


def step(step_id, evidence, participants, operation, temperature=None, time=None, stage="reaction"):
    s = st.new_step(step_id, evidence, stage=stage)
    s["participant_ids"] = list(participants)
    s["operation"] = f(operation, operation, evidence)
    if temperature is not None:
        s["temperature"] = f(temperature[0], temperature[1], evidence)
    if time is not None:
        s["time"] = f(time[0], time[1], evidence)
    return s


def outcome(oid, kind, targets, evidence, raw, normalized, *, basis=None,
            yield_type=None, scope=None, role="main_product"):
    o = st.new_outcome(oid, kind, targets, evidence)
    o["product_role"] = f(role, role, evidence)
    o["value"] = f(raw, normalized, evidence)
    if yield_type:
        o["yield_type"] = f(yield_type, yield_type, evidence)
    if basis:
        o["measurement_basis"] = f(basis, basis, evidence)
    if scope:
        o["scope"] = f(scope, scope, evidence)
    return o


def classification(evidence, codes=(), limitation=None):
    changes = []
    labels = []
    elements = {"C-C": ("C", "C"), "C-N": ("C", "N"), "C-O": ("C", "O"),
                "C-H": ("C", "H"), "C-F": ("C", "F")}
    numbers = {"C-H": 1, "C-C": 2, "C-O": 3, "C-N": 5, "C-F": 7}
    for i, code in enumerate(codes, 1):
        cid = f"b{i}"
        a, b = elements[code]
        ctype = "hydrogen_gain" if code == "C-H" else "formed"
        change = {"change_id": cid, "atoms": [{"atom_map": None, "element": a}, {"atom_map": None, "element": b}],
                  "before_order": 0, "after_order": 1, "change_type": ctype}
        if code == "C-H":
            change["hydrogen_count"] = 1
        changes.append(derived(change, evidence, "Partial bond-change assignment from the source reactant/product drawings; atom mapping is unavailable."))
        labels.append({"category_number": numbers[code], "code": code, "supporting_change_ids": [cid]})
    return {
        "standard_id": st.STANDARD,
        "mapped_reaction_smiles": f(evidence=evidence),
        "bond_changes": changes,
        "labels": inferred(labels, evidence, "Taxonomy labels are derived only from the explicitly retained new bonds."),
        "coverage": inferred("partial" if codes else "unresolved", evidence,
                             "No complete atom mapping is available; hydrogen transfers, bond-order changes, and omitted partners remain unresolved."),
        "limitations": [limitation or "Partial source-drawing classification; complete atom correspondence and implicit-H accounting remain unresolved."],
        "model_votes": [],
    }


def base_reaction(rid, page, record_type, categories, location, name, transformation,
                  general=(), codes=(), unresolved=()):
    evidence = ev(page)
    r = st.new_reaction(f"{DOC}:{rid}", DOC, evidence)
    r["record_type"] = record_type
    r["experiment_categories"] = (f(str(categories), categories, evidence)
                                      if categories is not None else f(evidence=evidence))
    r["location"] = f(location, {"page": page, "region": location}, evidence)
    r["general_scheme_ids"] = list(general)
    r["reaction_name"] = f(name, name, evidence) if name else f(evidence=evidence)
    r["transformation_type"] = f(transformation, transformation, evidence) if transformation else f(evidence=evidence)
    r["classification"] = classification(evidence, codes)
    r["review"] = {"status": "needs_review", "method": "model", "reviewer": None,
                   "checked_fields": [], "unresolved": list(unresolved) or [
                       "Machine-extracted record requires expert review; schema validation is not chemical certification."
                   ]}
    r["completeness"] = "partial"
    REACTIONS.append(r)
    return r


def set_solvent(r, evidence, composition=None, volume=None):
    if composition:
        r["solvent_conditions"]["composition"] = f(composition, composition, evidence)
    if volume:
        r["solvent_conditions"]["total_volume"] = f(volume[0], volume[1], evidence)


