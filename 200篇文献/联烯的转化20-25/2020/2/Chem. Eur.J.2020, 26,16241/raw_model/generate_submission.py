def add_molecule(mid, label, name, evidence, *, smiles=None, chirality="unresolved",
                 geometry="unresolved", representation=None, stereo_note=None,
                 identity_note=None, aliases=None):
    m = st.new_molecule(mid, DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = F(label, label, evidence)
    m["names"]["original"] = F(name, name, evidence)
    m["names"]["english"] = F(name, name, evidence)
    if aliases:
        m["names"]["aliases"] = F(aliases, aliases, evidence)
    m["cas_numbers"] = F(evidence=evidence)
    if smiles:
        diag = st.stereo_inspect(smiles)
        stereo_diagnostics[mid] = diag
        m["representation_type"] = "smiles"
        m["smiles"] = derived(smiles, evidence,
            "Candidate SMILES transcribed from the named/simple source structure; RDKit parsing is not source verification.")
        m["stereochemistry"]["isomeric_smiles"] = derived(
            diag["canonical_isomeric_smiles"], evidence,
            "Generated by the standard stereo graph diagnostic from the candidate SMILES.")
        m["stereochemistry"]["identity_key"] = derived(
            diag["stereo_graph_key"], evidence,
            "Generated by the standard stereo graph diagnostic; this is not a sample identity.")
        m["stereochemistry"]["atom_centers"] = derived(
            diag["atom_centers"], evidence, "Standard stereo graph diagnostic on the candidate SMILES.")
        m["stereochemistry"]["double_bonds"] = derived(
            diag["double_bonds"], evidence, "Standard stereo graph diagnostic on the candidate SMILES.")
        m["stereochemistry"]["axial"] = inferred(
            None, evidence, "No axial assignment was made by the graph diagnostic or source.")
        rep = representation or "encoded"
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = F(evidence=evidence)
        m["stereochemistry"]["atom_centers"] = (
            F(stereo_note, stereo_note, evidence) if stereo_note else F(evidence=evidence))
        m["stereochemistry"]["double_bonds"] = F(evidence=evidence)
        m["stereochemistry"]["axial"] = F(evidence=evidence)
        m["stereochemistry"]["isomeric_smiles"] = F(evidence=evidence)
        m["stereochemistry"]["identity_key"] = F(evidence=evidence)
        rep = representation or ("not_encoded" if stereo_note else "unresolved")
    m["stereochemistry"]["chirality_status"] = inferred(
        chirality, evidence,
        "Status assigned from explicit source wedges/names/ligand configuration and the available representation; absence of a label was not treated as achiral.")
    m["stereochemistry"]["geometry_status"] = inferred(
        geometry, evidence,
        "Status assigned from the source drawing/prose; unlabeled alkene geometry remains unspecified.")
    m["stereochemistry"]["representation_status"] = inferred(
        rep, evidence,
        "Reports whether the candidate representation preserves the source stereochemical information.")
    if stereo_note:
        m["stereochemistry"]["assignment"] = F(stereo_note, stereo_note, evidence)
    m["identity_note"] = F(
        identity_note or ("Simple named/source-drawn molecule; candidate SMILES remains machine-extracted." if smiles
                          else "Compact source drawing was not forced into an unverified complete SMILES."),
        identity_note or ("Simple named/source-drawn molecule; candidate SMILES remains machine-extracted." if smiles
                          else "Compact source drawing was not forced into an unverified complete SMILES."), evidence)
    molecules[mid] = m
    return m


