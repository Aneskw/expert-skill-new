def ev(page: int) -> list[str]:
    return [f"{DOC}:page{page}:image", f"{DOC}:page{page}:text"]


def F(raw=None, normalized=None, evidence=(), method="original_extraction", status=None, derivation=None):
    if normalized is None and raw is not None and method == "original_extraction":
        normalized = raw
    return st.fact(raw, normalized, evidence, method=method, status=status, derivation=derivation)


def derived(normalized, evidence, derivation, raw="source structure drawing"):
    return F(raw, normalized, evidence, method="structure_derivation", derivation=derivation)


def inferred(normalized, evidence, derivation, raw="source fact interpreted under extraction rules"):
    return F(raw, normalized, evidence, method="inference", derivation=derivation)


def qty(number, unit, **extra):
    return {"number": number, "unit": unit, **extra}


def raw_quantity(value):
    """Render a source-style scalar without converting the normalized object to repr()."""
    if isinstance(value, dict) and "number" in value and "unit" in value:
        number = value["number"]
        number_text = f"{number:g}" if isinstance(number, (int, float)) else str(number)
        qualifier = {"lt": "<", "le": "≤", "gt": ">", "ge": "≥", "approx": "~"}.get(value.get("qualifier"), "")
        return value.get("raw_text") or f"{qualifier}{number_text} {value['unit']}"
    return str(value)


