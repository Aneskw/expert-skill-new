def set_classification(r, evidence, labels=None, limitation=None, not_applicable=False):
    c = r["classification"]
    if not_applicable:
        c["labels"] = inferred([], evidence, "No observed preparative transformation is asserted for this contextual/generic record.")
        c["coverage"] = inferred("not_applicable", evidence, "No observed transformation to classify.")
        c["limitations"] = [limitation or "Contextual record; no observed bond changes asserted."]
        return
    if labels is None:
        c["coverage"] = inferred("unresolved", evidence, "Source drawing/retrosynthetic relation is not sufficiently atom-mapped for classification.")
        c["limitations"] = [limitation or "No complete atom mapping; bond classification remains unresolved."]
        return
    changes, label_by_code = [], {}
    for i, code in enumerate(labels, 1):
        a, b, order = label_atoms[code]
        cid = f"b{i}"
        change = {"change_id": cid,
                  "atoms": [{"atom_map": None, "element": a}, {"atom_map": None, "element": b}],
                  "before_order": 0, "after_order": order,
                  "change_type": "hydrogen_gain" if b == "H" else "formed"}
        changes.append(derived(change, evidence,
            "Partial net bond-change assignment from the source transformation; atom identities are not fully mapped."))
        row = st.bond_label(a, b, order)
        if row["code"] not in label_by_code:
            row["supporting_change_ids"] = []
            label_by_code[row["code"]] = row
        label_by_code[row["code"]]["supporting_change_ids"].append(cid)
    c["bond_changes"] = changes
    c["labels"] = derived(list(label_by_code.values()), evidence,
        "Taxonomy labels generated from all asserted formed/promoted bonds in the partial change list.")
    c["coverage"] = inferred("partial", evidence,
        "Only unambiguous newly formed bond classes are asserted; complete atom mapping, broken bonds, coproducts, and proton sources remain unresolved.")
    c["limitations"] = [limitation or "Partial source-derived bond classes; complete atom mapping and mass balance are unavailable."]


reactions: list[dict] = []


def new_rx(suffix, page, *, record_type="specific_experiment", categories=None,
           location=None, name=None, transformation=None, extra_evidence=()):
    evidence = list(dict.fromkeys(ev(page) + list(extra_evidence)))
    r = st.new_reaction(f"{DOC}:{suffix}", DOC, evidence)
    r["record_type"] = record_type
    r["experiment_categories"] = F(categories or (["other"] if record_type == "specific_experiment" else []),
                                      categories or (["other"] if record_type == "specific_experiment" else []), evidence)
    r["location"] = F(location or f"PDF page {page}", {"page": page, "region": location or "source region"}, evidence)
    if name: r["reaction_name"] = F(name, name, evidence)
    if transformation:
        r["transformation_type"] = inferred(transformation, evidence,
            "Normalized transformation name derived from the source caption/prose.", raw=name or transformation)
    r["review"] = {"status": "needs_review", "method": "model", "reviewer": None,
                   "checked_fields": [], "unresolved": []}
    r["completeness"] = "partial"
    reactions.append(r)
    return r


def add_solvents(r, evidence, mids, composition=None, concentration=None, ratio=None, volume=None):
    for i, mid in enumerate(mids, 1):
        add_participant(r, f"solvent_{i}", mid, "solvent", evidence)
    if composition:
        r["solvent_conditions"]["composition"] = F(composition, composition, evidence)
    if concentration is not None:
        r["solvent_conditions"]["concentration"] = F(raw_quantity(concentration), concentration, evidence)
    if ratio is not None:
        r["solvent_conditions"]["mixture_ratio"] = F(ratio, ratio, evidence)
    if volume is not None:
        r["solvent_conditions"]["total_volume"] = F(raw_quantity(volume), volume, evidence)


