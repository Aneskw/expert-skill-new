def add_participant(r, pid, mid, role, evidence, *, stage="reaction", mass=None,
                    amount=None, volume=None, equiv=None, molpct=None, ref=None,
                    product_role=None):
    p = st.new_participant(pid, mid, role, evidence, stage=stage)
    if product_role:
        p["product_role"] = F(product_role, product_role, evidence)
    for key, val in (("mass", mass), ("amount", amount), ("volume", volume),
                     ("equivalents", equiv), ("mol_percent", molpct)):
        if val is not None:
            p["charges"][key] = F(raw_quantity(val), val, evidence)
    if ref:
        p["equivalence_reference"] = inferred(
            ref, evidence, "Denominator assigned to the explicitly drawn/charged reference substrate; the source does not restate the denominator for every loading.",
            raw=f"loading/equivalents shown relative to reaction substrate; assigned reference {ref}")
    r["participants"].append(p)
    return p


def add_step(r, sid, evidence, pids, *, operation=None, temp=None, time=None,
             atmosphere=None, pressure=None, stage="reaction"):
    s = st.new_step(sid, evidence, stage=stage)
    s["participant_ids"] = list(pids)
    if operation is not None: s["operation"] = F(operation, operation, evidence)
    if temp is not None: s["temperature"] = F(raw_quantity(temp), temp, evidence)
    if time is not None: s["time"] = F(raw_quantity(time), time, evidence)
    if atmosphere is not None: s["atmosphere"] = F(atmosphere, atmosphere, evidence)
    if pressure is not None: s["pressure"] = F(raw_quantity(pressure), pressure, evidence)
    r["steps"].append(s)
    return s


def add_outcome(r, oid, kind, targets, evidence, value=None, *, yield_type=None,
                basis=None, scope=None, product_role="main product"):
    o = st.new_outcome(oid, kind, targets, evidence)
    if product_role: o["product_role"] = F(product_role, product_role, evidence)
    if value is not None: o["value"] = F(raw_quantity(value), value, evidence)
    if yield_type is not None: o["yield_type"] = F(yield_type, yield_type, evidence)
    if basis is not None: o["measurement_basis"] = F(basis, basis, evidence)
    if scope is not None: o["scope"] = F(scope, scope, evidence)
    r["outcomes"].append(o)
    return o


