def f(raw=None, normalized=None, ev=(), method="original_extraction", status=None,
      derivation=None, alternatives=()):
    return st.fact(raw, normalized, ev, method=method, status=status,
                   derivation=derivation, alternatives=alternatives)


def missing(ev=(), status="unreported"):
    return f(ev=ev, status=status)


def derived(value, ev, why):
    return f(None, value, ev, method="inference", derivation=why)


def mol(mid, label, ev, name=None, smiles=None, chirality="unresolved",
        geometry="unresolved", representation=None, stereo_note=None):
    m = st.new_molecule(mid, DOC, ev)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, ev)
    m["names"]["original"] = f(name or label, name or label, ev)
    m["names"]["english"] = f(name, name, ev) if name else missing(ev)
    m["names"]["abbreviations"] = f(label, [label], ev) if label != (name or label) else missing(ev)
    m["names"]["aliases"] = missing(ev)
    m["cas_numbers"] = missing(ev)
    m["generic_template"] = None
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = f(
            {"source": "candidate transcription from source drawing/name"}, smiles, ev,
            method="structure_derivation",
            derivation="Candidate connectivity transcribed from the source drawing/name; RDKit parsing is diagnostic only.",
        )
        m["stereochemistry"]["isomeric_smiles"] = f(
            None, diag["canonical_isomeric_smiles"], ev, method="structure_derivation",
            derivation="Canonical isomeric SMILES generated by the standard stereo graph diagnostic from the candidate SMILES.",
        )
        m["stereochemistry"]["identity_key"] = f(
            None, diag["stereo_graph_key"], ev, method="structure_derivation",
            derivation="Stereo graph key generated by the standard stereo diagnostic; not a sample identity assertion.",
        )
        rep = representation or "encoded"
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = missing(ev)
        m["stereochemistry"]["isomeric_smiles"] = missing(ev)
        m["stereochemistry"]["identity_key"] = missing(ev)
        rep = representation or "not_encoded"
    m["stereochemistry"]["chirality_status"] = derived(
        chirality, ev, "Status assigned conservatively from the inspected source drawing; missing stereomarks are not treated as racemic or achiral."
    )
    m["stereochemistry"]["geometry_status"] = derived(
        geometry, ev, "Status assigned conservatively from the inspected source drawing and ring/alkene context."
    )
    m["stereochemistry"]["representation_status"] = derived(
        rep, ev, "Reports whether the candidate molecular representation preserves the source-visible stereochemical information."
    )
    for key in ("atom_centers", "double_bonds", "axial", "mixture", "assignment"):
        m["stereochemistry"][key] = missing(ev)
    if stereo_note:
        m["stereochemistry"]["assignment"] = f(stereo_note, stereo_note, ev)
    m["identity_note"] = f(
        "Source label/drawing retained; no CAS lookup was performed."
        + (" Complete complex structure was not safely transcribed to SMILES." if not smiles else " Candidate SMILES remains machine-generated and needs review."),
        "Source identity retained; no external identity merge.", ev,
    )
    m["external_properties"] = []
    return m


def template_mol(mid, label, ev, fixed, variables, reason):
    m = mol(mid, label, ev, name=label, chirality="unresolved", geometry="unresolved", representation="not_encoded")
    m["representation_type"] = "generic_template"
    m["smiles"] = missing(ev)
    m["generic_template"] = {
        "fixed_structure": f(fixed, fixed, ev),
        "variables": [
            {
                "label": v,
                "attachment_points": f(f"Source drawing attachment for {v}", f"source-depicted attachment for {v}", ev),
                "definition": f(f"Variable {v} in source drawing", f"source-defined {v}", ev),
                "allowed_values": missing(ev),
                "constraints": missing(ev),
            }
            for v in variables
        ],
        "instance_mapping": [],
        "reason": f(reason, reason, ev),
    }
    return m


def participant(pid, mid, role, ev, stage="reaction", amounts=None, ref=None, product_role=None):
    p = st.new_participant(pid, mid, role, ev, stage=stage)
    if product_role is not None:
        p["product_role"] = f(product_role, product_role, ev)
    if amounts:
        for key, raw, val in amounts:
            p["charges"][key] = f(raw, val, ev)
    if ref:
        p["equivalence_reference"] = f(ref, ref, ev)
    return p


def step(sid, stage, pids, ev, operation=None, temperature=None, time=None):
    s = st.new_step(sid, ev, stage=stage)
    s["participant_ids"] = list(pids)
    if operation is not None:
        s["operation"] = f(operation, operation, ev)
    if temperature is not None:
        raw, value = temperature
        s["temperature"] = f(raw, value, ev)
    if time is not None:
        raw, value = time
        s["time"] = f(raw, value, ev)
    return s


def reaction(rid, ev, record_type="specific_experiment", categories=(), location=None,
             name=None, transform=None):
    r = st.new_reaction(f"{DOC}:{rid}", DOC, ev)
    r["record_type"] = record_type
    r["experiment_categories"] = f(list(categories), list(categories), ev)
    r["location"] = f(location, location, ev)
    r["reaction_name"] = f(name, name, ev) if name else missing(ev)
    r["transformation_type"] = derived(transform, ev, "Transformation description inferred from the source-depicted connectivity change.") if transform else missing(ev)
    r["review"] = {
        "status": "needs_review", "method": "model", "reviewer": None, "checked_fields": [],
        "unresolved": ["Machine extraction requires expert source and structure review."],
    }
    r["completeness"] = "partial"
    return r


def set_solvent(r, raw, normalized, ev, volume=None, concentration=None, basis=None):
    r["solvent_conditions"]["composition"] = f(raw, normalized, ev)
    if volume:
        r["solvent_conditions"]["total_volume"] = f(volume[0], volume[1], ev)
    if concentration:
        r["solvent_conditions"]["concentration"] = f(concentration[0], concentration[1], ev)
    if basis:
        r["solvent_conditions"]["concentration_basis"] = f(basis, basis, ev)


def add_outcome(r, oid, kind, targets, ev, raw=None, value=None, yield_type=None,
                basis=None, scope=None, status=None, alternatives=()):
    o = st.new_outcome(oid, kind, targets, ev)
    o["value"] = f(raw, value, ev, status=status, alternatives=alternatives)
    if yield_type is not None:
        o["yield_type"] = f(yield_type, yield_type, ev)
    if basis is not None:
        o["measurement_basis"] = f(basis, basis, ev)
    if scope is not None:
        o["scope"] = f(scope, scope, ev)
    r["outcomes"].append(o)
    return o


def classify(r, changes, ev, coverage="partial", limitations=()):
    change_facts = []
    labels = {}
    for i, (a, b, before, after, kind) in enumerate(changes, 1):
        item = {
            "change_id": f"b{i}",
            "atoms": [{"atom_map": None, "element": a}, {"atom_map": None, "element": b}],
            "before_order": before,
            "after_order": after,
            "change_type": kind,
        }
        if kind in ("hydrogen_gain", "hydrogen_loss"):
            item["hydrogen_count"] = 1
        change_facts.append(f(None, item, ev, method="structure_derivation",
                              derivation="Partial net bond change inferred from the inspected source scheme; exact atom mapping is unresolved."))
        if kind in ("formed", "order_increased", "hydrogen_gain"):
            lab = st.bond_label(a, b, after)
            labels.setdefault(lab["code"], {**lab, "supporting_change_ids": []})["supporting_change_ids"].append(f"b{i}")
    r["classification"]["bond_changes"] = change_facts
    r["classification"]["labels"] = f(
        None, list(labels.values()), ev, method="structure_derivation",
        derivation="Taxonomy labels generated from the explicitly retained partial bond changes.",
    )
    r["classification"]["coverage"] = derived(
        coverage, ev, "Coverage is partial/unresolved because complete atom mapping and coproduct accounting are unavailable from the supplied pages."
    )
    r["classification"]["limitations"] = list(limitations) or [
        "No complete atom mapping was asserted.",
        "Hydrogen/proton sources and unshown coproducts remain unresolved.",
    ]
    r["classification"]["model_votes"] = []


def no_transform(r, ev, why="No observed product; intended chemistry is not classified as a bond-forming event."):
    r["classification"]["bond_changes"] = []
    r["classification"]["labels"] = derived([], ev, why)
    r["classification"]["coverage"] = derived("not_applicable", ev, why)
    r["classification"]["limitations"] = [why]
    r["classification"]["model_votes"] = []


