def f(raw=None, norm=MISSING, ev=(), method="original_extraction", status=None,
      verification=None, derivation=None, alternatives=()):
    if norm is MISSING:
        norm = raw
    return st.fact(raw, norm, ev, method=method, status=status,
                   verification=verification, derivation=derivation,
                   alternatives=alternatives)


def inferred(norm, ev, derivation):
    return f(None, norm, ev, method="inference", derivation=derivation)


def derived(norm, ev, derivation):
    return f(None, norm, ev, method="structure_derivation", derivation=derivation)


def qty(raw, number, unit, ev, qualifier=None):
    value = {"number": number, "unit": unit, "raw_text": raw}
    if qualifier:
        value["qualifier"] = qualifier
    return f(raw, value, ev)


def source_molecule(mid, label, name=None, ev=(), smiles=None, chirality="unspecified",
                    geometry="unspecified", stereo_detail=None, mixture=None):
    m = st.new_molecule(mid, DOC, ev)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, ev)
    m["names"]["original"] = f(name or label, name or label, ev)
    if name:
        m["names"]["english"] = f(name, name, ev)
    m["identity_note"] = f(
        "Identity is retained from the source label/drawing; complex structures were not converted to a concrete SMILES unless explicitly noted.",
        "Source-labelled identity; machine record requires expert structure review.", ev)
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = derived(
            diag["canonical_isomeric_smiles"], ev,
            "Candidate SMILES derived from the explicitly named/simple drawn compound; RDKit parsing and canonicalization do not verify the paper drawing.")
        m["stereochemistry"]["chirality_status"] = derived(
            chirality, ev, "Stereo diagnostics were run on the candidate graph; source identity remains needs_review.")
        m["stereochemistry"]["geometry_status"] = derived(
            geometry, ev, "Geometry status was derived from the candidate graph and source drawing; unreported stereochemistry was not invented.")
        m["stereochemistry"]["representation_status"] = derived(
            "encoded", ev, "The candidate graph has been encoded as an isomeric SMILES; this is not source verification.")
        m["stereochemistry"]["isomeric_smiles"] = derived(
            diag["canonical_isomeric_smiles"], ev, "Generated by standard stereo diagnostics from the candidate SMILES.")
        m["stereochemistry"]["identity_key"] = derived(
            diag["stereo_graph_key"], ev, "Generated by standard stereo diagnostics; not a sample identity.")
        m["stereochemistry"]["atom_centers"] = derived(
            diag["atom_centers"], ev, "RDKit graph diagnostic, not an experimental assignment.")
        m["stereochemistry"]["double_bonds"] = derived(
            diag["double_bonds"], ev, "RDKit graph diagnostic; aromatic bonds are not E/Z assignments.")
    else:
        m["representation_type"] = "unresolved"
        if stereo_detail:
            m["stereochemistry"]["atom_centers"] = f(stereo_detail, stereo_detail, ev)
            m["stereochemistry"]["assignment"] = f(stereo_detail, stereo_detail, ev)
        if mixture:
            m["stereochemistry"]["mixture"] = f(mixture, mixture, ev)
        m["stereochemistry"]["chirality_status"] = inferred(
            chirality, ev, "Status preserves visible wedges/ee/mixture statements or the absence of a source assignment; no R/S value was inferred.")
        m["stereochemistry"]["geometry_status"] = inferred(
            geometry, ev, "No unreported E/Z or ring cis/trans assignment was invented from the unresolved drawing.")
        m["stereochemistry"]["representation_status"] = inferred(
            "not_encoded", ev, "The complete source structure/stereochemistry was not safely encoded as SMILES.")
    return m


def generic_molecule(mid, label, fixed, variables, ev):
    m = source_molecule(mid, label, label, ev)
    m["representation_type"] = "generic_template"
    m["generic_template"] = {
        "fixed_structure": f(fixed, fixed, ev),
        "variables": [
            {
                "label": v,
                "attachment_points": f(f"source-labelled attachment point for {v}", f"source-labelled attachment point for {v}", ev),
                "definition": f("not fully enumerated in the main-text generic drawing", "not fully enumerated in the main-text generic drawing", ev),
                "allowed_values": f(),
                "constraints": f(),
            }
            for v in variables
        ],
        "instance_mapping": [],
        "reason": f("The source uses R/X/Nu variables.", "Generic main-text drawing; a concrete SMILES would invent substituents.", ev),
    }
    return m


MOLECULES = {}


def add_molecule(m):
    MOLECULES[m["molecule_id"]] = m
    return m["molecule_id"]


def ensure(mid, label, name=None, ev=(), **kwargs):
    if mid not in MOLECULES:
        add_molecule(source_molecule(mid, label, name, ev, **kwargs))
    return mid


def set_charge(p, key, fact):
    p["charges"][key] = fact


def participant(pid, mid, role, ev, stage="reaction", charges=None, ref=None, product_role=None):
    p = st.new_participant(pid, mid, role, ev, stage=stage)
    if product_role:
        p["product_role"] = f(product_role, product_role, ev)
    for key, value in (charges or {}).items():
        p["charges"][key] = value
    if ref:
        p["equivalence_reference"] = f(ref, ref, ev)
    return p


def classification(kind, ev, description=None, count=1):
    c = st.new_reaction(f"{DOC}:temporary", DOC, ev)["classification"]
    if kind == "none":
        c["labels"] = inferred([], ev, "No observed transformation was reported; expected-product bonds were not classified.")
        c["coverage"] = inferred("not_applicable", ev, "No reaction/no product was observed.")
        c["limitations"] = ["Negative-control classification; no intended bond formation was asserted."]
        return c
    if kind == "unresolved":
        c["coverage"] = inferred("unresolved", ev, "The generic/literature arrow does not support a complete atom mapping.")
        c["limitations"] = ["No source-supported atom mapping was available."]
        return c
    element_pair = {
        "C-C": ("C", "C", 1, 2),
        "C-N": ("C", "N", 1, 5),
        "C-O": ("C", "O", 1, 3),
        "DB-C-C": ("C", "C", 2, 13),
    }[kind]
    a, b, order, number = element_pair
    changes = []
    for i in range(count):
        changes.append({
            "change_id": f"b{i+1}",
            "atoms": [{"atom_map": None, "element": a}, {"atom_map": None, "element": b}],
            "before_order": 0,
            "after_order": order,
            "change_type": "formed",
            "source_description": description or "bond formation indicated by the source transformation",
        })
    c["bond_changes"] = [derived(x, ev, "Partial bond change derived from the source arrow/text; atom mapping is unavailable.") for x in changes]
    c["labels"] = derived([
        {"category_number": number, "code": kind, "supporting_change_ids": [x["change_id"] for x in changes]}
    ], ev, "Taxonomy label computed from the recorded partial bond change(s).")
    c["coverage"] = inferred("partial", ev, "Only the clearly indicated new bond class was retained; complete atom mapping was not available.")
    c["limitations"] = [
        "No atom-mapped reaction SMILES was asserted.",
        "Additional ring-opening, proton-transfer, bond-order, or leaving-group changes may be present and remain unresolved.",
    ]
    return c


def reaction(rid, ev, record_type="specific_experiment", categories=None, location=None,
             name=None, transformation=None, bond="unresolved", bond_description=None,
             bond_count=1, unresolved=None):
    r = st.new_reaction(f"{DOC}:{rid}", DOC, ev)
    r["record_type"] = record_type
    r["experiment_categories"] = f(categories or [], categories or [], ev)
    r["location"] = f(location or rid, location or rid, ev)
    if name:
        r["reaction_name"] = f(name, name, ev)
    if transformation:
        r["transformation_type"] = f(transformation, transformation, ev)
    r["classification"] = classification(bond, ev, bond_description, bond_count)
    r["review"] = {
        "status": "needs_review",
        "method": "model",
        "reviewer": None,
        "checked_fields": [],
        "unresolved": list(unresolved or []),
    }
    r["completeness"] = "partial"
    return r


def step(step_id, ev, participants, operation, temperature=None, time=None, stage="reaction"):
    s = st.new_step(step_id, ev, stage=stage)
    s["participant_ids"] = list(participants)
    s["operation"] = f(operation, operation, ev)
    if temperature is not None:
        raw, norm = temperature
        s["temperature"] = f(raw, norm, ev)
    if time is not None:
        raw, norm = time
        s["time"] = f(raw, norm, ev)
    return s


def outcome(oid, kind, targets, ev, raw, norm=MISSING, product_role=None,
            yield_type=None, basis=None, scope=None):
    o = st.new_outcome(oid, kind, targets, ev)
    o["value"] = f(raw, norm, ev)
    if product_role:
        o["product_role"] = f(product_role, product_role, ev)
    if yield_type:
        o["yield_type"] = f(yield_type, yield_type, ev)
    if basis:
        o["measurement_basis"] = f(basis, basis, ev)
    if scope is not None:
        o["scope"] = f(scope, scope, ev)
    return o


def percent(raw, number=None, qualifier=None):
    if number is None:
        return raw
    v = {"number": number, "unit": "%", "raw_text": raw}
    if qualifier:
        v["qualifier"] = qualifier
    return v


def add_solvent_condition(r, raw, volume=None, ev=()):
    r["solvent_conditions"]["composition"] = f(raw, raw, ev)
    if volume:
        r["solvent_conditions"]["total_volume"] = qty(volume, float(volume.split()[0]), volume.split()[1], ev)


def add_standard_workup(r, ev):
    cotton = ensure("m_absorbent_cotton", "absorbent cotton", "absorbent cotton", ev)
    silica = ensure("m_silica", "SiO2", "silica gel", ev)
    r["participants"].append(participant(f"p_{r['reaction_id'].split(':')[-1]}_cotton", cotton, "workup_agent", ev, stage="workup"))
    r["participants"].append(participant(f"p_{r['reaction_id'].split(':')[-1]}_silica", silica, "purification_agent", ev, stage="purification"))
    ids = [p["participant_id"] for p in r["participants"]]
    r["steps"].append(step("workup_filter", ev, ids, "filtered through absorbent cotton", stage="workup"))
    r["steps"].append(step("workup_evaporate", ev, ids, "solvent was removed under reduced pressure", stage="workup"))
    r["steps"].append(step("purification_flash", ev, ids, "flash column chromatography (SiO2)", stage="purification"))


def ee_outcome(oid, target, raw, ev, basis="HPLC on a chiral stationary phase", scope=None):
    numeric = raw.rstrip("%")
    if numeric.startswith(">"):
        norm = percent(raw, float(numeric[1:]), "gt")
    else:
        norm = percent(raw, float(numeric))
    return outcome(oid, "selectivity", [target], ev, raw, norm,
                   product_role="major enantiomer not assigned",
                   basis=basis,
                   scope=scope or {"metric": "ee", "major_configuration": "unassigned"})


