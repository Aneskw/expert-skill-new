def step(step_id, stage, pids, evidence, operation, *, temperature=None, time=None,
         temp_method="original_extraction", temp_derivation=None):
    s = st.new_step(step_id, evidence, stage=stage)
    s["participant_ids"] = list(pids)
    s["operation"] = F(operation, operation, evidence)
    if temperature is not None:
        raw, norm = temperature
        s["temperature"] = F(raw, norm, evidence, method=temp_method,
                              derivation=temp_derivation)
    if time is not None:
        s["time"] = F(time[0], time[1], evidence)
    return s


def outcome(oid, kind, target, evidence, value, *, yield_type=None,
            basis=None, scope=None):
    o = st.new_outcome(oid, kind, [mid(target)], evidence)
    o["value"] = F(value[0], value[1], evidence)
    if yield_type is not None:
        o["yield_type"] = F(yield_type, yield_type, evidence)
    if basis is not None:
        o["measurement_basis"] = F(basis, basis, evidence)
    if scope is not None:
        o["scope"] = F(scope, scope, evidence)
    o["product_role"] = F("main product" if kind in ("yield", "product_amount") else "measured target",
                           "main product" if kind in ("yield", "product_amount") else "measured target", evidence)
    return o


