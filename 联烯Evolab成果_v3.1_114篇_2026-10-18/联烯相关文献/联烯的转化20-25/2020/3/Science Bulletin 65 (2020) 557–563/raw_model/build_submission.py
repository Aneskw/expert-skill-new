def tev(page: int) -> str:
    return f"{DOC}:page{page}:text"


def iev(page: int) -> str:
    return f"{DOC}:page{page}:image"


def ev(*pages: int) -> list[str]:
    result: list[str] = []
    for page in pages:
        result.extend([tev(page), iev(page)])
    return result


def F(raw=None, normalized=None, evidence=(), method="original_extraction",
      status=None, derivation=None, alternatives=()):
    if normalized is None and raw is not None:
        normalized = raw
    return st.fact(raw, normalized, evidence, method=method, status=status,
                   derivation=derivation, alternatives=alternatives)


def inferred(normalized, evidence, derivation, raw=None):
    return F(raw, normalized, evidence, method="inference", derivation=derivation)


def missing(evidence=(), status="unreported"):
    return st.fact(evidence=evidence, status=status)


def set_stereo(m, evidence, chirality, geometry, representation,
               assignment=None, axial=None, mixture=None, isomeric_smiles=None,
               identity_key=None, derivation=None):
    reason = derivation or "Stereochemical status assessed from the cited source drawing or name; no unreported configuration is supplied."
    m["stereochemistry"]["chirality_status"] = inferred(chirality, evidence, reason)
    m["stereochemistry"]["geometry_status"] = inferred(geometry, evidence, reason)
    m["stereochemistry"]["representation_status"] = inferred(representation, evidence, reason)
    if assignment is not None:
        m["stereochemistry"]["assignment"] = F(assignment, assignment, evidence)
    if axial is not None:
        m["stereochemistry"]["axial"] = F(axial, axial, evidence)
    if mixture is not None:
        m["stereochemistry"]["mixture"] = F(mixture, mixture, evidence)
    if isomeric_smiles is not None:
        m["stereochemistry"]["isomeric_smiles"] = inferred(
            isomeric_smiles, evidence,
            "Canonical isomeric SMILES generated from the candidate registry SMILES; toolkit output is not source verification.",
        )
    if identity_key is not None:
        m["stereochemistry"]["identity_key"] = inferred(
            identity_key, evidence,
            "Stereo graph key generated by standard stereo from the candidate registry SMILES.",
        )


def molecule(mid, label, pages, name=None, *, smiles=None,
             chirality="unresolved", geometry="unresolved",
             representation="not_encoded", assignment=None,
             identity_note=None):
    evidence = ev(*pages)
    m = st.new_molecule(f"{DOC}:{mid}", DOC, evidence)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = F(label, label, evidence)
    m["names"]["original"] = F(name or label, name or label, evidence)
    m["names"]["english"] = F(name or label, name or label, evidence)
    m["names"]["abbreviations"] = F(label, [label], evidence)
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = inferred(
            smiles, evidence,
            "Candidate SMILES transcribed from the source structure and checked for graph/stereo syntax with standard stereo; source identity remains needs_review.",
            raw=f"source drawing labelled {label}",
        )
        # Keep concrete allene candidates partial when the toolkit reports
        # potential but unassigned stereochemistry; parsing is not a claim that
        # every source stereochemical feature is encoded.
        representation = "partial"
        set_stereo(m, evidence, chirality, geometry, representation,
                   assignment=assignment,
                   isomeric_smiles=diag["canonical_isomeric_smiles"],
                   identity_key=diag["stereo_graph_key"])
    else:
        m["representation_type"] = "unresolved"
        set_stereo(m, evidence, chirality, geometry, representation,
                   assignment=assignment)
    note = identity_note or (
        "Source-labelled molecule retained without a complete SMILES because the dense structure or exact stereochemical encoding was not independently verified."
        if not smiles else
        "Machine candidate structure; parsing and stereo diagnostics do not establish correspondence to the source drawing."
    )
    m["identity_note"] = F(note, note, evidence)
    return m


def generic_molecule(mid, label, pages, fixed, variables, *,
                     chirality="unspecified", geometry="unspecified"):
    evidence = ev(*pages)
    m = molecule(mid, label, pages, name=label, chirality=chirality,
                 geometry=geometry, representation="not_encoded",
                 identity_note="Generic R-group structure from Scheme 1; retained as a template, not a concrete SMILES.")
    m["representation_type"] = "generic_template"
    m["generic_template"] = {
        "fixed_structure": F(fixed, fixed, evidence),
        "variables": [
            {
                "label": v[0],
                "attachment_points": F(v[1], v[1], evidence),
                "definition": F(v[2], v[2], evidence),
                "allowed_values": missing(evidence),
                "constraints": missing(evidence),
            }
            for v in variables
        ],
        "instance_mapping": [],
        "reason": F("Scheme 1 uses variable substituents.",
                    "Scheme 1 is a generic transformation and does not define a single concrete molecule.", evidence),
    }
    if chirality == "specified":
        m["stereochemistry"]["assignment"] = F(
            "Scheme marks the generic product/catalyst as stereogenic or chiral without a complete named configuration.",
            "Source-specified chirality; absolute configuration is not fully defined in the generic scheme.", evidence,
        )
    return m


def mid(short: str) -> str:
    return f"{DOC}:{short}"


def participant(pid, mol, role, evidence, *, stage="reaction", amount=None,
                mass=None, volume=None, equivalents=None, mol_percent=None,
                reference=None, product_role=None):
    p = st.new_participant(pid, mid(mol), role, evidence, stage=stage)
    if product_role is not None:
        p["product_role"] = F(product_role, product_role, evidence)
    for key, value in (("amount", amount), ("mass", mass), ("volume", volume),
                       ("equivalents", equivalents), ("mol_percent", mol_percent)):
        if value is not None:
            p["charges"][key] = F(value[0], value[1], evidence)
    if reference:
        p["equivalence_reference"] = inferred(
            mid(reference), evidence,
            "The source states equivalents/mol% relative to the named limiting substrate.",
            raw=f"relative to {reference}",
        )
    return p


def reaction_base(short, evidence, record_type, categories, location,
                  reaction_name, transformation):
    r = st.new_reaction(f"{DOC}:{short}", DOC, evidence)
    r["record_type"] = record_type
    r["experiment_categories"] = F(categories, categories, evidence)
    r["location"] = F(location, location, evidence)
    r["reaction_name"] = F(reaction_name, reaction_name, evidence)
    r["transformation_type"] = inferred(
        transformation, evidence,
        "Transformation type normalized from the source reaction name and depicted bond changes.",
        raw=reaction_name,
    )
    r["review"]["unresolved"] = []
    r["completeness"] = "partial"
    return r


def set_classification(r, evidence, changes, coverage="partial", limitations=None):
    labels = {}
    for change in changes:
        if change["change_type"] in ("formed", "hydrogen_gain", "order_increased"):
            lab = st.bond_label(change["atoms"][0]["element"], change["atoms"][1]["element"], change["after_order"])
            labels.setdefault(lab["code"], {**lab, "supporting_change_ids": []})["supporting_change_ids"].append(change["change_id"])
    derivation = "Partial net bond-change interpretation from the source drawings; no atom-mapped complete reaction is asserted."
    r["classification"]["bond_changes"] = [
        F(None, change, evidence, method="structure_derivation", derivation=derivation)
        for change in changes
    ]
    r["classification"]["labels"] = F(None, list(labels.values()), evidence,
                                           method="structure_derivation", derivation=derivation)
    r["classification"]["coverage"] = inferred(coverage, evidence, derivation)
    r["classification"]["limitations"] = limitations or [
        "Complex source structures were not atom mapped.",
        "Labels cover only source-visible net newly formed/promoted bonds; omitted partners and proton sources remain unresolved.",
    ]
    r["classification"]["model_votes"] = []


