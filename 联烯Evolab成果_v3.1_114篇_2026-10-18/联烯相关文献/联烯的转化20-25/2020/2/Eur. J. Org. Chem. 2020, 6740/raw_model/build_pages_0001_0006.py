def source(raw, normalized=None, ev=(), status="pending_review"):
    if normalized is None:
        normalized = raw
    return st.fact(raw, normalized, ev, status=status)


def inferred(normalized, ev, derivation, raw=None):
    return st.fact(raw, normalized, ev, method="structure_derivation", status="pending_review",
                   verification="inferred", derivation=derivation)


def missing(status="unreported"):
    return st.fact(status=status)


def not_applicable():
    return st.fact(method="not_applicable", status="not_applicable")


def set_status(m, key, value, ev, derivation):
    m["stereochemistry"][key] = inferred(value, ev, derivation)


def molecule(mid, label, name, pages, *, smiles=None, stereo=None, identity_note=None):
    ev = [E[p] for p in pages]
    m = st.new_molecule(mid, DOC, ev)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = source(label, label, ev)
    m["names"]["original"] = source(name, name, ev)
    m["names"]["english"] = source(name, name, ev)
    m["cas_numbers"] = missing()
    m["identity_note"] = source(identity_note, identity_note, ev) if identity_note else missing()
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = inferred(smiles, ev, "Candidate SMILES derived from the unambiguous source name/drawing; parsing is not source verification.")
        m["stereochemistry"]["atom_centers"] = inferred(diag["atom_centers"], ev, "RDKit standard stereo diagnostic on the candidate SMILES.")
        m["stereochemistry"]["double_bonds"] = inferred(diag["double_bonds"], ev, "RDKit standard stereo diagnostic on the candidate SMILES.")
        m["stereochemistry"]["axial"] = inferred([], ev, "No axial assignment is represented by this candidate SMILES; toolkit support is limited.")
        m["stereochemistry"]["mixture"] = not_applicable()
        m["stereochemistry"]["assignment"] = inferred("No stereogenic element detected in the candidate graph.", ev, "RDKit found no potential stereogenic element.")
        atom_unspecified = any(p["type"].startswith("Atom_") and p["specified"] == "Unspecified" for p in diag["potential_stereo"])
        bond_unspecified = any(p["type"].startswith("Bond_") and p["specified"] == "Unspecified" for p in diag["potential_stereo"])
        set_status(m, "chirality_status", "unspecified" if atom_unspecified else "achiral", ev,
                   "Standard stereo inspection found an unspecified potential atom stereoelement." if atom_unspecified else "Candidate graph has no potential atom stereocenter; this is a structure-derived machine statement.")
        set_status(m, "geometry_status", "unspecified" if bond_unspecified else "not_applicable", ev,
                   "Standard stereo inspection found an unspecified potential bond/cumulene stereoelement." if bond_unspecified else "Candidate graph has no E/Z-applicable stereogenic double bond.")
        set_status(m, "representation_status", "partial" if (atom_unspecified or bond_unspecified) else "encoded", ev,
                   "Candidate isomeric SMILES leaves a potential stereoelement unspecified." if (atom_unspecified or bond_unspecified) else "Candidate isomeric SMILES and graph key were generated by standard stereo inspection.")
        m["stereochemistry"]["isomeric_smiles"] = inferred(diag["canonical_isomeric_smiles"], ev, "Canonical isomeric SMILES from standard stereo inspection.")
        m["stereochemistry"]["identity_key"] = inferred(diag["stereo_graph_key"], ev, "Stereo graph key from standard stereo inspection; not a sample identity.")
        STEREO_CHECKS[mid] = diag
    else:
        m["representation_type"] = "unresolved"
        m["smiles"] = missing()
        m["generic_template"] = None
        stinfo = stereo or {}
        for key in ("atom_centers", "double_bonds", "axial", "mixture", "assignment"):
            value = stinfo.get(key)
            m["stereochemistry"][key] = source(value, value, ev) if value is not None else missing()
        set_status(m, "chirality_status", stinfo.get("chirality_status", "unresolved"), ev,
                   stinfo.get("chirality_reason", "The source identity was inspected, but a complete stereochemical graph was not encoded."))
        set_status(m, "geometry_status", stinfo.get("geometry_status", "unresolved"), ev,
                   stinfo.get("geometry_reason", "Alkene geometry is not fully assigned/encoded from the inspected source region."))
        set_status(m, "representation_status", stinfo.get("representation_status", "not_encoded"), ev,
                   "The complex or generic source drawing was deliberately not converted to an unverified complete SMILES.")
        m["stereochemistry"]["isomeric_smiles"] = missing()
        m["stereochemistry"]["identity_key"] = missing()
    return m


def generic_molecule(mid, label, page, description):
    ev = [E[page]]
    m = molecule(mid, label, description, [page], stereo={
        "chirality_status": "unresolved", "geometry_status": "unresolved",
        "representation_status": "not_encoded",
        "assignment": "Generic R-group structure; stereochemical state depends on substituents."
    }, identity_note="Generic source structure with R-group variables; not a concrete compound identity.")
    m["representation_type"] = "generic_template"
    m["generic_template"] = {
        "fixed_structure": source(description, {"source_drawing": label, "description": description}, ev),
        "variables": [
            {"label": r, "attachment_points": source(f"{r} attachment in {label}", f"source-drawn {r} attachment", ev),
             "definition": st.fact(f"{r} not defined on pages 1–6", None, ev, status="unreadable"),
             "allowed_values": missing(), "constraints": missing()}
            for r in ("R1", "R2", "R3")
        ],
        "instance_mapping": [],
        "reason": source("Scheme uses R1/R2/R3", "Generic structure retained because the substituents are not instantiated.", ev),
    }
    return m


def participant(pid, mid, role, ev, *, stage="reaction", amount=None, equiv=None, reference=None, product_role=None):
    p = st.new_participant(pid, mid, role, ev, stage)
    if product_role is not None:
        p["product_role"] = source(product_role, product_role, ev)
    if amount is not None:
        p["charges"]["amount"] = source(amount, amount, ev)
    if equiv is not None:
        p["charges"]["equivalents"] = source(f"{equiv} equivalents", {"number": equiv, "unit": "equiv"}, ev)
        p["equivalence_reference"] = source(reference, reference, ev)
    return p


def reaction(suffix, ev, record_type, categories, location, name, transformation, unresolved):
    r = st.new_reaction(f"{DOC}:{suffix}", DOC, ev)
    r["record_type"] = record_type
    r["experiment_categories"] = source(categories, categories, ev) if categories is not None else not_applicable()
    r["location"] = source(location, location, ev)
    r["reaction_name"] = source(name, name, ev) if name else missing()
    r["transformation_type"] = inferred(transformation, ev, "Transformation class interpreted from the source drawing/text.") if transformation else missing()
    r["review"] = {"status": "needs_review", "method": "model", "reviewer": None,
                   "checked_fields": [], "unresolved": list(unresolved)}
    r["completeness"] = "partial"
    return r


def add_step(r, sid, ev, pids, operation, *, temperature=None, time=None, stage="reaction"):
    s = st.new_step(sid, ev, stage)
    s["participant_ids"] = pids
    s["operation"] = source(operation, operation, ev)
    if temperature is not None:
        s["temperature"] = source(str(temperature), temperature, ev)
    if time is not None:
        s["time"] = source(str(time), time, ev)
    r["steps"].append(s)
    return s


def add_outcome(r, oid, kind, targets, ev, raw, normalized, *, role=None, basis=None, scope=None, yield_type=None):
    o = st.new_outcome(oid, kind, targets, ev)
    o["value"] = source(raw, normalized, ev)
    if role is not None:
        o["product_role"] = source(role, role, ev)
    if basis is not None:
        o["measurement_basis"] = source(basis, basis, ev)
    if scope is not None:
        o["scope"] = source(scope, scope, ev)
    if yield_type is not None:
        o["yield_type"] = source(yield_type, yield_type, ev)
    r["outcomes"].append(o)
    return o


def set_classification(r, ev, changes, limitations):
    labels = {}
    for change in changes:
        if change["change_type"] in ("formed", "hydrogen_gain", "order_increased"):
            lab = st.bond_label(change["atoms"][0]["element"], change["atoms"][1]["element"], change["after_order"])
            labels.setdefault(lab["code"], dict(lab, supporting_change_ids=[]))["supporting_change_ids"].append(change["change_id"])
    r["classification"]["bond_changes"] = [inferred(c, ev, "Partial element-level bond change derived from the source reaction drawing.") for c in changes]
    r["classification"]["labels"] = inferred(list(labels.values()), ev, "Labels are exactly the formed/promoted bonds in the retained partial bond changes.")
    r["classification"]["coverage"] = inferred("partial", ev, "No complete atom-mapped reaction graph was asserted.")
    r["classification"]["limitations"] = list(limitations)


def set_no_reaction_classification(r, ev):
    r["classification"]["bond_changes"] = []
    r["classification"]["labels"] = inferred([], ev, "No observed transformation; no expected-product bond label was invented.")
    r["classification"]["coverage"] = inferred("not_applicable", ev, "Negative stability control with no observed reaction.")
    r["classification"]["limitations"] = ["No-reaction observation does not establish a complete detection limit."]


