def ensure_new(identifier, registry, kind):
    if identifier in registry:
        raise RuntimeError(f"Refusing to overwrite existing {kind}: {identifier}")


def add_molecule(
    molecule_id,
    label,
    name,
    *,
    identity_status="source_identified",
    smiles=None,
    chirality="unresolved",
    geometry="unresolved",
    representation="not_encoded",
    axial=None,
    mixture=None,
    note,
):
    ensure_new(molecule_id, molecules, "molecule")
    m = st.new_molecule(molecule_id, DOC, EV)
    m["identity_status"] = identity_status
    m["occurrences"][0]["compound_label"] = original(label)
    m["names"]["original"] = original(name)
    m["names"]["english"] = original(name)
    m["cas_numbers"] = st.fact()
    if smiles:
        diag = st.stereo_inspect(smiles)
        m["representation_type"] = "smiles"
        m["smiles"] = derived(
            smiles,
            "Connectivity candidate derived from the unambiguous systematic name in footnote 20; parsing is not source identity verification.",
        )
        m["stereochemistry"]["isomeric_smiles"] = derived(
            diag["canonical_isomeric_smiles"],
            "Canonical isomeric SMILES generated by the standard stereo checker; the source does not assign the allene axis.",
        )
        m["stereochemistry"]["identity_key"] = derived(
            diag["stereo_graph_key"],
            "Stereo graph key generated by the standard stereo checker for the source-derived candidate graph.",
        )
    else:
        m["representation_type"] = "unresolved"
    if axial is not None:
        m["stereochemistry"]["axial"] = inferred(
            axial,
            "The named allene can have an axial stereochemical element, but footnote 20 gives no R_a/S_a or P/M assignment; toolkit axial support is limited.",
        )
    if mixture is not None:
        m["stereochemistry"]["mixture"] = original(mixture[0], mixture[1])
    m["stereochemistry"]["chirality_status"] = inferred(
        chirality,
        "Status assigned after inspecting the page-7 name/result; missing stereochemical assignment is not treated as achiral or racemic.",
    )
    m["stereochemistry"]["geometry_status"] = inferred(
        geometry,
        "No E/Z or ring cis/trans assignment is stated on page 7; allene axial stereochemistry is tracked under chirality rather than E/Z geometry.",
    )
    m["stereochemistry"]["representation_status"] = inferred(
        representation,
        "Compares the page-7 identity/stereochemical information with the stored representation; unassigned allene axes and unresolved products are not claimed as encoded.",
    )
    m["identity_note"] = original(note)
    molecules[molecule_id] = m
    bundle["molecules"].append(m)
    return m


def participant(participant_id, molecule_id, role):
    return st.new_participant(participant_id, molecule_id, role, EV)


def classification_core():
    c = st.new_reaction(f"{DOC}:classification_scaffold", DOC, EV)["classification"]
    changes = [
        ("b1", "formed", "C", "C", 0, 1),
        ("b2", "broken", "C", "O", 1, 0),
        ("b3", "hydrogen_loss", "C", "H", 1, 0),
    ]
    c["bond_changes"] = []
    for cid, change_type, a, b, before, after in changes:
        change = {
            "change_id": cid,
            "atoms": [{"atom_map": None, "element": a}, {"atom_map": None, "element": b}],
            "before_order": before,
            "after_order": after,
            "change_type": change_type,
        }
        if change_type.startswith("hydrogen_"):
            change["hydrogen_count"] = 1
        c["bond_changes"].append(
            derived(
                change,
                "Partial net change inferred from the article's allene/N,O-acetal aminoalkylation context; no complete atom mapping is asserted.",
            )
        )
    c["labels"] = derived(
        [{"category_number": 2, "code": "C-C", "supporting_change_ids": ["b1"]}],
        "Only the newly formed C-C connection enters the bond-formation taxonomy; cleavage and C-H loss remain explicit changes.",
    )
    c["coverage"] = inferred(
        "partial",
        "The footnote does not display a complete mapped reaction or coproducts.",
    )
    c["limitations"] = [
        "Page-7 footnote supplies a transformation/result summary, not a complete atom-mapped structure set.",
        "No three-model vote was performed or fabricated.",
    ]
    c["model_votes"] = []
    return c


def classification_negative(reason):
    c = st.new_reaction(f"{DOC}:classification_scaffold", DOC, EV)["classification"]
    c["bond_changes"] = []
    c["labels"] = inferred([], "No observed bond formation is assigned for the negative/aggregate control statement.")
    c["coverage"] = inferred("not_applicable", reason)
    c["limitations"] = [reason, "No intended-product bond label or three-model vote was fabricated."]
    c["model_votes"] = []
    return c


def base_reaction(suffix, region, name, categories, transformation, classification):
    reaction_id = f"{DOC}:{suffix}"
    ensure_new(reaction_id, reactions, "reaction")
    r = st.new_reaction(reaction_id, DOC, EV)
    r["record_type"] = "specific_experiment"
    r["experiment_categories"] = original(categories, categories)
    r["location"] = original(
        f"PDF page 7, {region}", {"page": 7, "region": region}
    )
    r["reaction_name"] = original(name)
    r["transformation_type"] = inferred(
        transformation,
        "Concise experiment type inferred from the current-paper footnote statement.",
    )
    r["classification"] = classification
    r["review"] = {
        "status": "needs_review",
        "method": "model",
        "reviewer": None,
        "checked_fields": [],
        "unresolved": [],
    }
    r["completeness"] = "partial"
    reactions[reaction_id] = r
    bundle["reactions"].append(r)
    return r


