def add_molecule(mid, label, evidence, name=None, smiles=None, representation="unresolved",
                 chirality="unresolved", geometry="unresolved", representation_status=None,
                 stereo_assignment=None, double_bonds=None, generic_description=None):
    if mid in molecules:
        return molecules[mid]
    ev = list(dict.fromkeys(evidence))
    m = st.new_molecule(mid, DOC, ev)
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, ev)
    m["names"]["original"] = f(name or label, name or label, ev)
    m["names"]["english"] = f(name or label, name or label, ev)
    m["representation_type"] = representation
    if smiles:
        m["representation_type"] = "smiles"
        m["smiles"] = f(
            f"candidate structure for {label}", smiles, ev, method="structure_derivation",
            derivation="Candidate graph derived from the explicit source name; parsing does not establish source identity."
        )
        diag = st.stereo_inspect(smiles)
        m["stereochemistry"]["isomeric_smiles"] = f(
            None, diag["canonical_isomeric_smiles"], ev, method="structure_derivation",
            derivation="Canonical isomeric SMILES generated by standard stereo from the candidate source-derived graph."
        )
        m["stereochemistry"]["identity_key"] = f(
            None, diag["stereo_graph_key"], ev, method="structure_derivation",
            derivation="stereo_graph_key generated by standard stereo; it is not a sample identity."
        )
        representation_status = representation_status or (
            "partial" if any(x["specified"] == "Unspecified" for x in diag["potential_stereo"]) else "encoded"
        )
    elif representation == "generic_template":
        desc = generic_description or name or label
        m["generic_template"] = {
            "fixed_structure": f(desc, {"description": desc}, ev),
            "variables": [],
            "instance_mapping": [],
            "reason": f(
                "source-defined family or mixture without one complete concrete graph",
                "A single concrete SMILES would overstate the supplied source.", ev
            ),
        }
        representation_status = representation_status or "not_encoded"
    else:
        representation_status = representation_status or "not_encoded"
    m["stereochemistry"]["chirality_status"] = f(
        None, chirality, ev, method="inference",
        derivation="Status assigned conservatively from the cited drawing/name; absence of a descriptor is not treated as achiral or racemic."
    )
    m["stereochemistry"]["geometry_status"] = f(
        None, geometry, ev, method="inference",
        derivation="Status assigned conservatively from the cited drawing/name; drawn geometry is retained without inventing an E/Z descriptor."
    )
    m["stereochemistry"]["representation_status"] = f(
        None, representation_status, ev, method="inference",
        derivation="Representation status reflects what is encoded in the machine record, not whether the drawing is chemically correct."
    )
    if stereo_assignment:
        m["stereochemistry"]["assignment"] = f(stereo_assignment, stereo_assignment, ev)
    if double_bonds:
        m["stereochemistry"]["double_bonds"] = f(
            double_bonds, [{"feature": "alkene shown in Fig. 5", "configuration": "single drawn geometry; descriptor not reported"}],
            ev, method="structure_derivation",
            derivation="The source draws one geometry, but a complete graph and CIP E/Z assignment were not encoded."
        )
    m["identity_note"] = f(
        "Machine-created source identity; exact connectivity and stereochemistry require expert review.",
        "Machine-created source identity; exact connectivity and stereochemistry require expert review.", ev
    )
    molecules[mid] = m
    bundle["molecules"].append(m)
    return m


def add_family(mid, label, evidence, description, variables):
    m = add_molecule(mid, label, evidence, name=label, representation="generic_template",
                     chirality="unresolved", geometry="unresolved",
                     generic_description=description)
    m["generic_template"]["variables"] = [{
        "label": variable,
        "attachment_points": f(
            f"{variable} attachment in the source drawings",
            {"label": variable, "attachment": "source drawing"}, evidence
        ),
        "definition": f(
            "natural or unnatural amino-acid-derived segment",
            "source-defined amino-acid-derived segment", evidence
        ),
        "allowed_values": f(
            "instances incorporated in 6a-6h",
            "instances incorporated in 6a-6h", evidence
        ),
        "constraints": f(
            "complete identities and protecting-group histories are in unavailable SI pages 7-14",
            "not exhaustively defined in supplied main text", evidence
        ),
    } for variable in variables]
    return m


