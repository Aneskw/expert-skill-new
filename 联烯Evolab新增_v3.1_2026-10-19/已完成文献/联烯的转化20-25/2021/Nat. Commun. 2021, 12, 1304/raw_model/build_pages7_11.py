def participant(pid, mid, role, evidence, stage="reaction", amount=None, equivalents=None,
                mol_percent=None, volume=None, product_role=None, method="original_extraction",
                reference=None):
    p = st.new_participant(pid, mid, role, evidence, stage=stage)
    if product_role:
        p["product_role"] = f(product_role, product_role, evidence, method=method)
    if amount:
        p["charges"]["amount"] = f(amount[2], quantity(amount[0], amount[1], amount[2]), evidence, method=method)
    if equivalents:
        p["charges"]["equivalents"] = f(equivalents[1], quantity(equivalents[0], "equiv", equivalents[1]), evidence, method=method)
        p["equivalence_reference"] = f(reference, reference, evidence, method=method)
    if mol_percent:
        p["charges"]["mol_percent"] = f(mol_percent[1], quantity(mol_percent[0], "mol%", mol_percent[1]), evidence, method=method)
        p["equivalence_reference"] = f(reference, reference, evidence, method=method)
    if volume:
        p["charges"]["volume"] = f(volume[2], quantity(volume[0], volume[1], volume[2]), evidence, method=method)
    return p


def step(step_id, stage, operation_raw, evidence, participant_ids=(), temp=None, time=None,
         atmosphere=None, method="original_extraction"):
    s = st.new_step(step_id, evidence, stage=stage)
    s["participant_ids"] = list(participant_ids)
    s["operation"] = f(operation_raw, operation_raw, evidence, method=method)
    if temp:
        s["temperature"] = f(temp[2], quantity(temp[0], temp[1], temp[2]), evidence, method=method)
    if time:
        s["time"] = f(time[2], quantity(time[0], time[1], time[2]), evidence, method=method)
    if atmosphere:
        s["atmosphere"] = f(atmosphere, atmosphere, evidence, method=method)
    return s


