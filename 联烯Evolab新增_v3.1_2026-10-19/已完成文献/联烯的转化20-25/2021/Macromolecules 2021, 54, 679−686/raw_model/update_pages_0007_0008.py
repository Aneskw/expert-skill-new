#!/usr/bin/env python3
"""Add source-context and coverage decisions for visually inspected PDF pages 7-8.

Pages 7-8 contain the end of the conclusion, article metadata, and references.
They do not add a present-paper reaction experiment. Existing v3.1 molecules and
reactions are retained solely so that standard merge can update the whole dataset
atomically without duplicating prior page records.
"""
from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
RUN = ROOT / "runs/current"
DOC = "doc_0112e35a7f38a0ec"
GENERIC = f"{DOC}:scheme1_generic_polymerization"


def ev(page: int, kind: str) -> str:
    return f"{DOC}:page{page}:{kind}"


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def main() -> None:
    # The empty template is generated by `standard init` for this page batch.
    template = json.loads((RUN / "raw_model/pages_0007_0008_init.json").read_text())
    existing = json.loads((RUN / "standard_records.json").read_text())

    template["molecules"] = existing["molecules"]
    template["reactions"] = existing["reactions"]
    template["source_context"] = [
        item
        for item in existing["source_context"]
        if item.get("context_id")
        not in {f"{DOC}:page7_context", f"{DOC}:page8_context"}
    ]
    template["source_context"].extend(
        [
            {
                "context_id": f"{DOC}:page7_context",
                "document_id": DOC,
                "evidence_ids": [ev(7, "image"), ev(7, "text")],
                "page": 7,
                "kind": "conclusion_article_metadata_and_references",
                "finding": (
                    "The conclusion continues the present paper's general claim of "
                    "2,3-selective, helix-sense-selective polymerization but gives no "
                    "new conditions, quantities, products, or independent experiment. "
                    "The rest of the page contains an SI availability statement, author "
                    "information, acknowledgments, and references 1-15."
                ),
            },
            {
                "context_id": f"{DOC}:page8_context",
                "document_id": DOC,
                "evidence_ids": [ev(8, "image"), ev(8, "text")],
                "page": 8,
                "kind": "references",
                "finding": (
                    "The page contains references 16-47 only. Titles mentioning synthesis, "
                    "polymerization, allenes, catalysts, or helicity describe cited prior "
                    "literature and are not present-paper experiments."
                ),
            },
        ]
    )
    write_json(RUN / "submitted.json", template)

    coverage = {
        "document_id": DOC,
        "semantic_accuracy_verified": False,
        "pages": [
            {
                "page": 7,
                "state": "attempted",
                "regions": [
                    {
                        "region": "upper-left conclusion continuation",
                        "finding": (
                            "Present-paper conclusion summarizing the already-recorded generic "
                            "2,3-selective and helix-sense-selective polymerization; no new "
                            "reaction arrow, experimental row, quantities, or distinct experiment."
                        ),
                        "evidence_ids": [ev(7, "image"), ev(7, "text")],
                    },
                    {
                        "region": "Associated Content, author information, and acknowledgments",
                        "finding": (
                            "Administrative/source metadata. The page explicitly says Supporting "
                            "Information is available, but no SI file was supplied in this workspace, "
                            "so no SI association or SI-derived experiment was created."
                        ),
                        "evidence_ids": [ev(7, "image"), ev(7, "text")],
                    },
                    {
                        "region": "right-column references 1-15",
                        "finding": (
                            "Bibliographic citations to prior literature only; no current-paper "
                            "reaction records were created from citation titles."
                        ),
                        "evidence_ids": [ev(7, "image"), ev(7, "text")],
                    },
                ],
                "record_ids": [GENERIC],
                "unresolved": [
                    "The article states that SI exists, but the SI PDF was not provided or explicitly associated."
                ],
            },
            {
                "page": 8,
                "state": "attempted",
                "regions": [
                    {
                        "region": "full page, references 16-47",
                        "finding": (
                            "Reference list only. Several titles mention allene or polymerization "
                            "chemistry, but all are cited prior works rather than experiments of this paper. "
                            "No figures, tables, reaction arrows, experimental footnotes, or present-paper "
                            "procedures are present."
                        ),
                        "evidence_ids": [ev(8, "image"), ev(8, "text")],
                    }
                ],
                "record_ids": [],
                "unresolved": [],
            },
        ],
    }
    write_json(RUN / "coverage/pages_0007_0008.json", coverage)

    raw = {
        "document_id": DOC,
        "pages_visually_inspected": [7, 8],
        "inspection_basis": {
            "page7": "full rendered page image at original detail plus extracted page text",
            "page8": "full rendered page image at original detail plus extracted page text",
        },
        "page_decisions": [
            {
                "page": 7,
                "new_reaction_records": 0,
                "new_molecule_records": 0,
                "linked_existing_record_ids": [GENERIC],
                "nonreaction_content": [
                    "conclusion summary",
                    "SI availability statement",
                    "author information",
                    "acknowledgments",
                    "references 1-15",
                ],
            },
            {
                "page": 8,
                "new_reaction_records": 0,
                "new_molecule_records": 0,
                "linked_existing_record_ids": [],
                "nonreaction_content": ["references 16-47"],
            },
        ],
        "si_association": "unestablished",
        "chemical_accuracy_verified": False,
        "semantic_accuracy_verified": False,
    }
    write_json(RUN / "raw_model/extracted_pages_0007_0008.json", raw)

    print(
        json.dumps(
            {
                "pages": [7, 8],
                "new_molecules": 0,
                "new_reactions": 0,
                "total_molecules_in_submission": len(template["molecules"]),
                "total_reactions_in_submission": len(template["reactions"]),
                "source_context_entries": len(template["source_context"]),
            },
            ensure_ascii=False,
        )
    )


if __name__ == "__main__":
    main()
