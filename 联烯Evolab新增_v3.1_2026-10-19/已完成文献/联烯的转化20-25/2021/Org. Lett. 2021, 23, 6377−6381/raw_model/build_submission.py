def molecule(label, name, page, *, smiles=None, aliases=None, chirality="unresolved",
             geometry="unresolved", representation="unresolved", assignment=None,
             double_bonds=None, axial=None, mixture=None, note=None):
    m = st.new_molecule(mid(label), DOC, [EV[page], IMG[page]])
    m["identity_status"] = "source_identified"
    m["occurrences"][0]["compound_label"] = f(label, label, page)
    m["names"]["original"] = f(name, name, page)
    m["names"]["english"] = f(name, name, page)
    m["names"]["abbreviations"] = f(aliases or [], aliases or [], page) if aliases else missing(page)
    m["names"]["aliases"] = f(aliases or [], aliases or [], page) if aliases else missing(page)
    m["cas_numbers"] = missing(page)
    if smiles:
        m["representation_type"] = "smiles"
        m["smiles"] = f(None, smiles, page, method="structure_derivation",
                         derivation="Candidate connectivity transcribed from the cited name/drawing; parsing does not establish source correctness.")
        try:
            diag = st.stereo_inspect(smiles)
            m["stereochemistry"]["isomeric_smiles"] = f(
                None, diag["canonical_isomeric_smiles"], page, method="structure_derivation",
                derivation="Generated by the standard stereo diagnostic from the candidate SMILES.")
            m["stereochemistry"]["identity_key"] = f(
                None, diag["stereo_graph_key"], page, method="structure_derivation",
                derivation="Stereo graph key generated by the standard stereo diagnostic; not a sample identity.")
        except ValueError:
            pass
    else:
        m["representation_type"] = "unresolved"
    set_status(m, chirality, geometry, representation, page, assignment=assignment,
               double_bonds=double_bonds, axial=axial, mixture=mixture)
    if note:
        m["identity_note"] = f(note, note, page)
    bundle["molecules"].append(m)
    return m


