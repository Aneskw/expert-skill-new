def trimer_participants(r, substrate, product, catalyst, solvent, page, *, total_mmol, equiv,
                        catalyst_mmol=None, catalyst_mol=30, solvent_ml=None):
    prime = substrate + "p"
    ps = participant("substrate", mid(substrate), "reactant", page,
                     amount=(f"mixture of {substrate} and {substrate}′ ({total_mmol} mmol)", None),
                     equivalents=(f"mixture of {substrate} and {substrate}′ ({equiv} equiv)", None),
                     reference=mid(product))
    pp = participant("allenoate_component", mid(prime), "reactant", page)
    pc = participant("catalyst", mid(catalyst), "catalyst", page,
                     amount=(f"{catalyst_mmol} mmol", q(catalyst_mmol, "mmol")) if catalyst_mmol is not None else None,
                     mol_percent=(f"{catalyst_mol} mol%", q(catalyst_mol, "mol%")), reference=mid(product))
    psol = participant("solvent", mid(solvent), "solvent", page,
                       volume=(f"{solvent_ml} mL", q(solvent_ml, "mL")) if solvent_ml is not None else None)
    prod = participant("product", mid(product), "product", page, product_role="desired product")
    r["participants"] = [ps, pp, pc, psol, prod]
    r["reaction_scale"] = f(
        f"mixture of {substrate} and {substrate}′ ({total_mmol} mmol, {equiv} equiv)",
        {"reference_molecule_id": mid(substrate), "amount": q(total_mmol, "mmol"),
         "scope": "collective alkyne/allenoate mixture; not a component-specific amount"}, page)
    r["solvent_conditions"]["composition"] = f(solvent, [mid(solvent)], page)
    if solvent_ml is not None:
        r["solvent_conditions"]["total_volume"] = f(f"{solvent_ml} mL", q(solvent_ml, "mL"), page)
    r["notes"].append(f(
        f"The printed {total_mmol} mmol and {equiv} equiv apply to the combined {substrate}/{substrate}′ mixture, not separately to either component.",
        {"collective_charge": True, "components": [mid(substrate), mid(prime)]}, page))
    r["review"]["unresolved"].append("The source reports a collective alkyne/allenoate-mixture charge; component-specific mmol/equivalents are not reported.")


