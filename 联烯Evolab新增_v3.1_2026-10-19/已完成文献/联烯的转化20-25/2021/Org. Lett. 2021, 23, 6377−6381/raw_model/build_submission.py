def set_status(m, chirality, geometry, representation, page, *, assignment=None,
               double_bonds=None, axial=None, mixture=None, derivation=None):
    why = derivation or "Status assigned from the cited source label/drawing; machine record requires expert review."
    m["stereochemistry"]["chirality_status"] = inferred(chirality, page, why)
    m["stereochemistry"]["geometry_status"] = inferred(geometry, page, why)
    m["stereochemistry"]["representation_status"] = inferred(representation, page, why)
