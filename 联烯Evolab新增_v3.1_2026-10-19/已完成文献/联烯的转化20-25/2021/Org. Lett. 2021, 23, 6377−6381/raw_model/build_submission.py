def participant(pid, molecule_id, role, page, *, stage="reaction", amount=None,
                equivalents=None, mol_percent=None, volume=None, reference=None, product_role=None):
    p = st.new_participant(pid, molecule_id, role, [EV[page], IMG[page]], stage=stage)
    if product_role:
        p["product_role"] = f(product_role, product_role, page)
    values = {"amount": amount, "equivalents": equivalents, "mol_percent": mol_percent, "volume": volume}
    for key, item in values.items():
        if item is not None:
            raw, norm = item
            p["charges"][key] = f(raw, norm, page)
    if (equivalents is not None or mol_percent is not None) and reference:
        p["equivalence_reference"] = inferred(reference, page, "Reference follows the stated 3.0-equivalent trimerization convention; exact denominator convention requires expert review.")
    return p


def base_reaction(label, page, location, *, record_type="specific_experiment", categories=None,
                  name=None, transform=None):
    r = st.new_reaction(rid(label), DOC, [EV[page], IMG[page]])
    r["record_type"] = record_type
    r["experiment_categories"] = f(categories or [], categories or [], page)
    r["location"] = f(location, {"page": page, "location": location}, page)
    r["reaction_name"] = f(name, name, page) if name else missing(page)
    r["transformation_type"] = f(transform, transform, page) if transform else missing(page)
    r["review"] = {"status": "needs_review", "method": "model", "reviewer": None,
                   "checked_fields": [], "unresolved": []}
    r["completeness"] = "partial"
    return r


def set_classification(r, page, changes, labels, limitation):
    r["classification"]["mapped_reaction_smiles"] = missing(page)
    r["classification"]["bond_changes"] = [
        f(None, change, page, method="structure_derivation",
          derivation="Category-level change inferred from the cited reaction drawing; atom-complete mapping was not assigned.")
        for change in changes
    ]
    label_rows = []
    for code, ids in labels.items():
        row = next(x for x in st.read(ROOT / "skills/chemical-reaction-extraction/references/bond_taxonomy.json")["categories"] if x["code"] == code)
        label_rows.append({"category_number": row["number"], "code": code, "supporting_change_ids": ids})
    r["classification"]["labels"] = f(None, label_rows, page, method="structure_derivation",
                                           derivation="Labels cover only source-resolved newly formed/promoted bonds.")
    r["classification"]["coverage"] = inferred("partial" if changes else "unresolved", page, limitation)
    r["classification"]["limitations"] = [limitation, "No atom-mapped reaction SMILES was asserted."]


def c_c_classification(r, page):
    changes = [{"change_id": f"b{i}", "atoms": [{"atom_map": None, "element": "C"}, {"atom_map": None, "element": "C"}],
                "before_order": 0, "after_order": 1, "change_type": "formed"} for i in range(1, 4)]
    set_classification(r, page, changes, {"C-C": ["b1", "b2", "b3"]},
                       "The graphical abstract states three C-C bonds; exact atom correspondence and other bond-order changes remain unresolved.")


def no_classification(r, page, reason="No observed transformation to classify."):
    r["classification"]["mapped_reaction_smiles"] = missing(page)
    r["classification"]["bond_changes"] = []
    r["classification"]["labels"] = inferred([], page, reason)
    r["classification"]["coverage"] = inferred("not_applicable", page, reason)
    r["classification"]["limitations"] = [reason]


def add_step(r, page, participant_ids, temperature=None, time=None, operation="reaction"):
    s = st.new_step(f"{r['reaction_id'].split(':')[-1]}_reaction", [EV[page], IMG[page]])
    s["participant_ids"] = participant_ids
    s["operation"] = f(operation, operation, page)
    if temperature is not None:
        raw, norm = temperature
        s["temperature"] = f(raw, norm, page)
    if time is not None:
        raw, norm = time
        s["time"] = f(raw, norm, page)
    r["steps"].append(s)


def yield_outcome(label, target, value, page, *, basis="isolated", yield_type="reported product yield"):
    o = st.new_outcome(label, "yield", [target], [EV[page], IMG[page]])
    o["product_role"] = f("desired product", "desired product", page)
    o["value"] = f(f"{value}%", q(value, "%"), page)
    o["yield_type"] = f(yield_type, yield_type, page)
    if basis:
        o["measurement_basis"] = f(basis, basis, page)
    o["scope"] = f("single-step product yield", {"start": "reported reactant mixture", "end": target}, page)
    return o


